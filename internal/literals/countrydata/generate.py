#!/usr/bin/env python3
"""Generate internal/literals/countrydata/data.go from packages/landing-blocks/src/geo/generatedCountryTokens.ts."""
import json
import re
import pathlib

SRC = pathlib.Path("packages/landing-blocks/src/geo/generatedCountryTokens.ts")
OUT = pathlib.Path("internal/literals/countrydata/data.go")


def main():
    text = SRC.read_text()
    # Extract the object body between the first { and the final };
    start = text.find("{")
    end = text.rfind("};")
    if end == -1:
        end = text.rfind("}")
    body = text[start:end + 1]

    by_code: dict[str, dict[str, str]] = {}
    by_name: dict[str, dict[str, str]] = {}

    # Match each top-level country entry.
    # The code is the quoted key before the colon.
    for m in re.finditer(r'"([A-Z]{2})":\s*\{', body):
        code = m.group(1)
        brace = m.end() - 1
        depth = 1
        i = m.end()
        while i < len(body) and depth > 0:
            if body[i] == "{":
                depth += 1
            elif body[i] == "}":
                depth -= 1
            i += 1
        block = body[brace:i]

        def field(name: str) -> str:
            p = re.search(rf'"{name}":\s*"([^"]*)"', block)
            return p.group(1) if p else ""

        country = field("country")
        short = field("country_short")
        adj = field("country_adjective")
        if not adj:
            adj = field("demonym")  # fallback if any use demonym

        by_code[code] = {"Name": country, "Adjective": adj}

        names_match = re.search(r'"names":\s*\{([^}]*)\}', block)
        name = country
        if names_match:
            names_block = names_match.group(1)
            en_match = re.search(r'"en":\s*"([^"]*)"', names_block)
            if en_match:
                name = en_match.group(1)
        by_name[name.lower().strip()] = {"Code": code, "Adjective": adj}

    lines = [
        "// Code generated by internal/literals/countrydata/generate.py. DO NOT EDIT.",
        "package countrydata",
        "",
        "// Country holds the canonical name and adjective for an ISO country code.",
        "type Country struct {",
        "\tName      string",
        "\tCode      string",
        "\tAdjective string",
        "}",
        "",
        "var ByCode = map[string]Country{",
    ]
    for code in sorted(by_code):
        c = by_code[code]
        esc_name = c["Name"].replace('\\', '\\\\').replace('"', '\\"')
        esc_adj = c["Adjective"].replace('\\', '\\\\').replace('"', '\\"')
        lines.append(f'\t"{code}": {{Name: "{esc_name}", Adjective: "{esc_adj}"}},')
    lines.append("}")
    lines.append("")
    lines.append("var ByName = map[string]Country{")
    for name in sorted(by_name):
        c = by_name[name]
        esc_name = name.replace('\\', '\\\\').replace('"', '\\"')
        esc_adj = c["Adjective"].replace('\\', '\\\\').replace('"', '\\"')
        lines.append(f'\t"{esc_name}": {{Code: "{c["Code"]}", Adjective: "{esc_adj}"}},')
    lines.append("}")
    lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Generated {OUT} with {len(by_code)} countries.")


if __name__ == "__main__":
    main()
