// Campaign is the API-facing content_campaigns row.
type Campaign struct {
	ID                    string   `json:"id"`
	TenantID              string   `json:"tenant_id"`
	Name                  string   `json:"name"`
	Prompt                string   `json:"prompt"`
	Status                string   `json:"status"`
	ContentType           string   `json:"content_type,omitempty"`
	RequestedCount        int      `json:"requested_count"`
	PersonaPool           []string `json:"persona_pool,omitempty"`
	AutoProvisionPersonas bool     `json:"auto_provision_personas"`
	AutoAssign            bool     `json:"auto_assign"`
	TargetSpaceID         string   `json:"target_space_id,omitempty"`
	TargetTags            []string `json:"target_tags,omitempty"`
	PlanJSON              []byte   `json:"-"`
	ProvisionedPersonas   int      `json:"provisioned_personas"`
	CreatedBy             string   `json:"created_by"`
	CreatedAt             string   `json:"created_at"`
	UpdatedAt             string   `json:"updated_at"`
}

