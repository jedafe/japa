// CampaignItemPlan is a single item in the AI-generated content plan.
type CampaignItemPlan struct {
	PersonaID     string   `json:"persona_id"`
	ContentType   string   `json:"content_type"`
	Title         string   `json:"title"`
	TopicPrompt   string   `json:"topic_prompt"`
	TargetSpaceID string   `json:"target_space_id,omitempty"`
	TargetTags    []string `json:"target_tags,omitempty"`
}

// PersonaSpec is a proposed new AI persona generated by the planner.
// ActivityPolicy is optional; the persona provisioning layer applies defaults
// when it is empty.
type PersonaSpec struct {
	Name           string         `json:"name"`
	Slug           string         `json:"slug"`
	Tagline        string         `json:"tagline,omitempty"`
	VoicePrompt    string         `json:"voice_prompt"`
	ActivityPolicy map[string]any `json:"activity_policy,omitempty"`
}

// CampaignPlanResult is the output of Planner.PlanContent.
// NewPersonas is populated by PlanPersonas and included here for the response
// envelope; PlanContent itself only returns Items.
type CampaignPlanResult struct {
	NewPersonas []PersonaSpec    `json:"new_personas,omitempty"`
	Items       []CampaignItemPlan `json:"items"`
}

// campaignFromGen converts a generated ContentCampaign row to the API DTO.
func campaignFromGen(c gen.ContentCampaign) Campaign {
	camp := Campaign{
		ID:                    c.ID.String(),
		TenantID:              c.TenantID.String(),
		Name:                  c.Name,
		Prompt:                c.Prompt,
		Status:                c.Status,
		RequestedCount:        int(c.RequestedCount),
		AutoProvisionPersonas: c.AutoProvisionPersonas,
		AutoAssign:            c.AutoAssign,
		TargetTags:            c.TargetTags,
		PlanJSON:              c.PlanJson,
		ProvisionedPersonas:   countNewPersonas(c.PlanJson),
		CreatedBy:             c.CreatedBy.String(),
		CreatedAt:             formatTimestamp(c.CreatedAt),
		UpdatedAt:             formatTimestamp(c.UpdatedAt),
	}
	if c.ContentType != nil {
		camp.ContentType = *c.ContentType
	}
	if c.PersonaPool != nil {
		camp.PersonaPool = make([]string, 0, len(c.PersonaPool))
		for _, p := range c.PersonaPool {
			if p.Valid {
				camp.PersonaPool = append(camp.PersonaPool, p.String())
			}
		}
	}
	if c.TargetSpaceID.Valid {
		camp.TargetSpaceID = c.TargetSpaceID.String()
	}
	return camp
}

// countNewPersonas extracts the number of auto-provisioned personas from the
// stored plan_json. Errors are silently ignored so a malformed plan_json does
// not break list/get responses.
func countNewPersonas(planJSON []byte) int {
	if len(planJSON) == 0 {
		return 0
	}
	var plan CampaignPlanResult
	if err := json.Unmarshal(planJSON, &plan); err != nil {
		return 0
	}
	return len(plan.NewPersonas)
}

// campaignItemFromGen converts a generated ContentCampaignItem row to the API DTO.
func campaignItemFromGen(i gen.ContentCampaignItem, personaNames map[string]string) CampaignItem {
	item := CampaignItem{
		ID:          i.ID.String(),
		CampaignID:  i.CampaignID.String(),
		SortOrder:   int(i.SortOrder),
		PersonaID:   i.PersonaID.String(),
		ContentType: i.ContentType,
		TopicPrompt: i.TopicPrompt,
		TargetTags:  i.TargetTags,
		Status:      i.Status,
		CreatedAt:   formatTimestamp(i.CreatedAt),
	}
	if name, ok := personaNames[i.PersonaID.String()]; ok {
		item.PersonaName = name
	}
	if i.Title != nil {
		item.Title = *i.Title
	}
	if i.TargetSpaceID.Valid {
		item.TargetSpaceID = i.TargetSpaceID.String()
	}
	if i.StudioJobID.Valid {
		item.StudioJobID = i.StudioJobID.String()
	}
	if i.ContentID.Valid {
		item.ContentID = i.ContentID.String()
	}
	if i.ReviewID.Valid {
		item.ReviewID = i.ReviewID.String()
	}
	if i.ErrorMessage != nil {
		item.ErrorMessage = *i.ErrorMessage
	}
	return item
}

func formatTimestamp(ts pgtype.Timestamptz) string {
	if !ts.Valid {
		return ""
	}
	return ts.Time.UTC().Format(time.RFC3339)
}
