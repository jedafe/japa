// buildCommunityOrgCreateParams maps a validated extraction to a
// CreateCommunityOrganisationIntelParams. DestinationSpaceID and CitySpaceID
// are resolved by the caller (communityOrgCreatePath) via GetCountrySpace
// and overridden after construction. GuideID is left NULL (Approach B:
// Studio generates the contents guide from the extraction data).
func buildCommunityOrgCreateParams(record gen.IntelRecord, source gen.IntelSource, ext extractor.Extraction) gen.CreateCommunityOrganisationIntelParams {
	name := stringField(ext, "name")
	if name == "" {
		name = source.Name
	}

	slug := stringField(ext, "slug")
	if slug == "" {
		slug = content.Slugify(name)
	}

	orgType := stringField(ext, "org_type")
	if orgType == "" {
		orgType = "other" // satisfy NOT NULL when the extractor omitted it
	}

	return gen.CreateCommunityOrganisationIntelParams{
		TenantID:           record.TenantID,
		Name:               name,
		Slug:               slug,
		OrgType:            orgType,
		OriginCommunity:    stringField(ext, "origin_community"),
		DestinationSpaceID: pgtype.UUID{}, // resolved by communityOrgCreatePath
		Address:            stringPtrField(ext, "address"),
		Latitude:           numericField(ext, "latitude"),
		Longitude:          numericField(ext, "longitude"),
		WebsiteUrl:         stringPtrField(ext, "website_url"),
		MeetingFrequency:   stringPtrField(ext, "meeting_frequency"),
		ContactInfo:        stringPtrField(ext, "contact_info"),
		Status:             "published",
		IsActive:           true,
		IntelRecordID:      record.ID,
		GuideID:            pgtype.UUID{}, // Approach B: NULL, Studio generates the guide
		ConfidenceOverall:  record.ConfidenceOverall,
		// spec §530: create path stamps 'verified' + 'ingestion'. The
		// community_organisations CHECK constraint only allows
		// verification_status IN ('verified','needs_review','conflict','stale')
		// and override_source IN ('ingestion','editorial','mixed').
		VerificationStatus: "verified",
		FreshnessScore:     freshScore,
		OverrideSource:     "ingestion",
		EditorialOverrides: emptyJSONObject(),
	}
}

// buildCommunityOrgUpdateParams produces an UpdateCommunityOrganisationIntelParams
// seeded from the existing row, then applies each extraction field that is
// NOT in overrides and whose value actually changed. It returns the params
// and the list of changed column names. Fields in editorial_overrides keep
// the existing value (human edit wins).
//
// slug, destination_space_id, and city_space_id are immutable on the update
// path (the UpdateCommunityOrganisationIntel query does not touch them), so
// they are not considered here.
func buildCommunityOrgUpdateParams(existing gen.CommunityOrganisation, ext extractor.Extraction, overrides map[string]struct{}) (gen.UpdateCommunityOrganisationIntelParams, []string) {
	params := gen.UpdateCommunityOrganisationIntelParams{
		TenantID:           existing.TenantID,
		ID:                 existing.ID,
		Name:               existing.Name,
		OrgType:            existing.OrgType,
		OriginCommunity:    existing.OriginCommunity,
		Address:            existing.Address,
		Latitude:           existing.Latitude,
		Longitude:          existing.Longitude,
		WebsiteUrl:         existing.WebsiteUrl,
		MeetingFrequency:   existing.MeetingFrequency,
		ContactInfo:        existing.ContactInfo,
		Status:             existing.Status,
		IsActive:           existing.IsActive,
		ConfidenceOverall:  existing.ConfidenceOverall,
		VerificationStatus: existing.VerificationStatus,
		FreshnessScore:     existing.FreshnessScore,
		OverrideSource:     existing.OverrideSource,
		EditorialOverrides: existing.EditorialOverrides,
	}

	var changed []string

	// name
	if _, ov := overrides["name"]; !ov {
		if v := stringField(ext, "name"); v != "" && v != existing.Name {
			params.Name = v

			changed = append(changed, "name")
		}
	}
	// org_type
	if _, ov := overrides["org_type"]; !ov {
		if v := stringField(ext, "org_type"); v != "" && v != existing.OrgType {
			params.OrgType = v

			changed = append(changed, "org_type")
		}
	}
	// origin_community
	if _, ov := overrides["origin_community"]; !ov {
		if v := stringField(ext, "origin_community"); v != "" && v != existing.OriginCommunity {
			params.OriginCommunity = v

			changed = append(changed, "origin_community")
		}
	}
	// address
	if _, ov := overrides["address"]; !ov {
		if v := stringPtrField(ext, "address"); !strPtrEqual(v, existing.Address) {
			params.Address = v

			changed = append(changed, "address")
		}
	}
	// latitude
	if _, ov := overrides["latitude"]; !ov {
		if v := numericField(ext, "latitude"); v.Valid && !numericEqual(v, existing.Latitude) {
			params.Latitude = v

			changed = append(changed, "latitude")
		}
	}
	// longitude
	if _, ov := overrides["longitude"]; !ov {
		if v := numericField(ext, "longitude"); v.Valid && !numericEqual(v, existing.Longitude) {
			params.Longitude = v

			changed = append(changed, "longitude")
		}
	}
	// website_url
	if _, ov := overrides["website_url"]; !ov {
		if v := stringPtrField(ext, "website_url"); !strPtrEqual(v, existing.WebsiteUrl) {
			params.WebsiteUrl = v

			changed = append(changed, "website_url")
		}
	}
	// meeting_frequency
	if _, ov := overrides["meeting_frequency"]; !ov {
		if v := stringPtrField(ext, "meeting_frequency"); !strPtrEqual(v, existing.MeetingFrequency) {
			params.MeetingFrequency = v

			changed = append(changed, "meeting_frequency")
		}
	}
	// contact_info
	if _, ov := overrides["contact_info"]; !ov {
		if v := stringPtrField(ext, "contact_info"); !strPtrEqual(v, existing.ContactInfo) {
			params.ContactInfo = v

			changed = append(changed, "contact_info")
		}
	}

	return params, changed
}

// marshalCommunityOrgFieldChanges builds the intel_review_log.field_changes
// JSON array capturing before/after values for each changed column.
func marshalCommunityOrgFieldChanges(existing gen.CommunityOrganisation, params gen.UpdateCommunityOrganisationIntelParams, changed []string) ([]byte, error) {
	changes := make([]fieldChange, 0, len(changed))

	for _, c := range changed {
		fc := fieldChange{Field: c}

		switch c {
		case "name":
			fc.From, fc.To = existing.Name, params.Name
		case "org_type":
			fc.From, fc.To = existing.OrgType, params.OrgType
		case "origin_community":
			fc.From, fc.To = existing.OriginCommunity, params.OriginCommunity
		case "address":
			fc.From, fc.To = derefStr(existing.Address), derefStr(params.Address)
		case "latitude":
			fc.From, fc.To = numericStr(existing.Latitude), numericStr(params.Latitude)
		case "longitude":
			fc.From, fc.To = numericStr(existing.Longitude), numericStr(params.Longitude)
		case "website_url":
			fc.From, fc.To = derefStr(existing.WebsiteUrl), derefStr(params.WebsiteUrl)
		case "meeting_frequency":
			fc.From, fc.To = derefStr(existing.MeetingFrequency), derefStr(params.MeetingFrequency)
		case "contact_info":
			fc.From, fc.To = derefStr(existing.ContactInfo), derefStr(params.ContactInfo)
		}

		changes = append(changes, fc)
	}

	return json.Marshal(changes)
}
