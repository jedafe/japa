// CommunityOrgStore is the persistence surface the CommunityOrgPromoter
// needs. *stores.Store satisfies this interface; tests substitute a mock.
//
// The community-organisation domain writes a community_organisations
// standalone projection row (via CreateCommunityOrganisationIntel /
// UpdateCommunityOrganisationIntel) and flips the intel record to
// 'extracted' status. The contents guide row is NOT created here — Studio
// generates it from the extraction data via intel_record_id (ADR-076
// Amendment 1, Approach B). WithTx runs the multi-table writes atomically
// (BUG-01/02 fix, §6.2 transaction boundary).
type CommunityOrgStore interface {
	PersonaResolver
	GetIntelRecord(ctx context.Context, id pgtype.UUID) (gen.IntelRecord, error)
	GetIntelSource(ctx context.Context, id pgtype.UUID) (gen.IntelSource, error)
	GetCommunityOrganisationByIntelRecord(ctx context.Context, intelRecordID pgtype.UUID) (gen.CommunityOrganisation, error)
	CreateCommunityOrganisationIntel(ctx context.Context, arg gen.CreateCommunityOrganisationIntelParams) (gen.CommunityOrganisation, error)
	UpdateCommunityOrganisationIntel(ctx context.Context, arg gen.UpdateCommunityOrganisationIntelParams) error
	UpdateIntelRecordStatus(ctx context.Context, arg gen.UpdateIntelRecordStatusParams) error
	CreateIntelReviewLog(ctx context.Context, arg gen.CreateIntelReviewLogParams) error
	// GetCountrySpace resolves the destination country-level geo space (§05)
	// id for an ISO-3 country code, so the promoter can stamp
	// community_organisations.destination_space_id. Returns
	// (pgtype.UUID{}, nil) when no country space exists yet. BUG-005 fix
	// (spec §455).
	GetCountrySpace(ctx context.Context, countryCode string) (pgtype.UUID, error)
	WithTx(ctx context.Context, fn func(CommunityOrgTxStore) error) error
}

// CommunityOrgTxStore is the subset of CommunityOrgStore needed inside a
// transaction. It exposes only the write methods that createPath and
// updatePath call, so the transactional store can be a narrower type.
// *stores.Store satisfies this interface (via WithTx's callback), and the
// test mock satisfies it directly.
type CommunityOrgTxStore interface {
	CreateCommunityOrganisationIntel(ctx context.Context, arg gen.CreateCommunityOrganisationIntelParams) (gen.CommunityOrganisation, error)
	UpdateIntelRecordStatus(ctx context.Context, arg gen.UpdateIntelRecordStatusParams) error
	UpdateCommunityOrganisationIntel(ctx context.Context, arg gen.UpdateCommunityOrganisationIntelParams) error
	CreateIntelReviewLog(ctx context.Context, arg gen.CreateIntelReviewLogParams) error
}

// CommunityOrgPromoter promotes community-organisation intel_records into
// the community_organisations projection table. It implements the
// editorial-override-respect invariant: on the update path, any field
// present in community_organisations.editorial_overrides is left untouched
// so a human edit always wins over a re-crawl. The contents guide row is
// generated by Studio from the extraction data (ADR-076 Amendment 1,
// Approach B: no contents write, guide_id=NULL, status='extracted').
type CommunityOrgPromoter struct {
	store    CommunityOrgStore
	authorID pgtype.UUID // system/automation user for review-log actor
	aiModel  *string     // AI model used for extraction (ADR-088, INTEL-003)
	now      func() time.Time
}

// CommunityOrgPromoterOption configures a CommunityOrgPromoter.
type CommunityOrgPromoterOption func(*CommunityOrgPromoter)

// WithCommunityOrgClock overrides the clock used for timestamps (tests).
func WithCommunityOrgClock(fn func() time.Time) CommunityOrgPromoterOption {
	return func(p *CommunityOrgPromoter) { p.now = fn }
}

// WithCommunityOrgAIModel sets the AI model name stamped on created rows
// (ADR-088).
func WithCommunityOrgAIModel(model string) CommunityOrgPromoterOption {
	return func(p *CommunityOrgPromoter) { p.aiModel = &model }
}

// NewCommunityOrgPromoter creates a promoter backed by the given store. The
// ID and authorID identify the platform stamped onto the
// community_organisations projection rows created by the create path and
// the system user credited as the review-log actor.
func NewCommunityOrgPromoter(store CommunityOrgStore, authorID pgtype.UUID, opts ...CommunityOrgPromoterOption) *CommunityOrgPromoter {
	p := &CommunityOrgPromoter{store: store, authorID: authorID, aiModel: ptr("gpt-4o-mini"), now: time.Now}
	for _, opt := range opts {
		opt(p)
	}

	return p
}

// Entity returns the entity_type this promoter handles.
func (p *CommunityOrgPromoter) Entity() string { return "community_organisation" }

// ErrNotCommunityOrg is returned when Promote is called on an intel record
// whose entity_type is not "community_organisation".
var ErrNotCommunityOrg = errors.New("promoter: intel record is not a community_organisation")

// Promote maps the intel record identified by recordID to a
// community_organisations projection row, creating it or updating it in
// place while respecting editorial overrides.
func (p *CommunityOrgPromoter) Promote(ctx context.Context, recordID uuid.UUID) (PromoteResult, error) {
	return promoteDomain(ctx, p.store, recordID, domainPromoteOps[gen.CommunityOrganisation]{
		entityType: p.Entity(),
		notErr:     ErrNotCommunityOrg,
		loadLabel:  "community organisation",
		getExisting: func(ctx context.Context, pgID pgtype.UUID) (gen.CommunityOrganisation, error) {
			return p.store.GetCommunityOrganisationByIntelRecord(ctx, pgID)
		},
		createPath: p.communityOrgCreatePath,
		updatePath: p.communityOrgUpdatePath,
	})
}

// communityOrgCreatePath inserts the community_organisations projection row
// and flips the intel record to 'extracted' status. The contents guide row
// is NOT created here — Studio generates it from the extraction data via
// intel_record_id (ADR-076 Amendment 1, Approach B: guide_id=NULL). Both
// writes run inside a single transaction so a failure in either rolls back
// the other (BUG-01 fix, §6.2).
//
// destination_space_id is NOT NULL on community_organisations, so when no
// country space can be resolved from the extracted country code the record
// is routed back to review rather than failing the promotion. BUG-005 fix
// (spec §455).
func (p *CommunityOrgPromoter) communityOrgCreatePath(ctx context.Context, record gen.IntelRecord, source gen.IntelSource, ext extractor.Extraction) (PromoteResult, error) {
	// Resolve the destination country's geo space (§05) so the
	// space-scoped feed can match this organisation.
	countryCode := firstCountry(ext, "country")

	var destinationSpaceID pgtype.UUID

	if countryCode != "" {
		if id, err := p.store.GetCountrySpace(ctx, countryCode); err == nil && id.Valid {
			destinationSpaceID = id
		}
	}

	if !destinationSpaceID.Valid {
		return PromoteResult{}, fmt.Errorf(
			"promoter: community organisation requires a destination country space but none resolved for %q: %w",
			countryCode, ErrRouteToReview,
		)
	}

	// Resolve the city-level geo space if a city was extracted. There is no
	// dedicated city-space lookup, so we fall back to GetCountrySpace with
	// the city name; when no match is found city_space_id stays NULL.
	var citySpaceID pgtype.UUID

	if city := stringField(ext, "city"); city != "" {
		if id, err := p.store.GetCountrySpace(ctx, city); err == nil && id.Valid {
			citySpaceID = id
		}
	}

	orgParams := buildCommunityOrgCreateParams(record, source, ext)
	orgParams.DestinationSpaceID = destinationSpaceID
	orgParams.CitySpaceID = citySpaceID

	var result PromoteResult

	err := p.store.WithTx(ctx, func(tx CommunityOrgTxStore) error {
		org, err := tx.CreateCommunityOrganisationIntel(ctx, orgParams)
		if err != nil {
			return fmt.Errorf("promoter: create community organisation: %w", err)
		}

		if err := tx.UpdateIntelRecordStatus(ctx, gen.UpdateIntelRecordStatusParams{
			ID:     record.ID,
			Status: "extracted",
		}); err != nil {
			return fmt.Errorf("promoter: mark intel record extracted: %w", err)
		}

		result = PromoteResult{
			DomainID:  pgToUUID(org.ID),
			ContentID: uuid.Nil,
			Action:    ActionCreated,
		}

		return nil
	})

	return result, err
}

// communityOrgUpdatePath applies the new extraction to the existing
// community_organisations row, skipping any field present in
// editorial_overrides, and records an auto_update review-log entry when
// fields actually change. The update and the review log write run inside a
// single transaction so the audit trail is always consistent with the
// projection state (BUG-02 fix, §6.2).
//
// slug, destination_space_id, and city_space_id are immutable on the update
// path (the UpdateCommunityOrganisationIntel query does not touch them), so
// the country/city extraction is only honored on the create path.
func (p *CommunityOrgPromoter) communityOrgUpdatePath(ctx context.Context, record gen.IntelRecord, existing gen.CommunityOrganisation, ext extractor.Extraction) (PromoteResult, error) {
	overrides, err := parseOverrideKeys(existing.EditorialOverrides)
	if err != nil {
		return PromoteResult{}, fmt.Errorf("promoter: parse editorial overrides: %w", err)
	}

	params, changed := buildCommunityOrgUpdateParams(existing, ext, overrides)
	params.FreshnessScore = freshScore

	var changesJSON []byte

	if len(changed) > 0 {
		if changesJSON, err = marshalCommunityOrgFieldChanges(existing, params, changed); err != nil {
			return PromoteResult{}, fmt.Errorf("promoter: marshal field changes: %w", err)
		}
	}

	return domainUpdateTx(ctx, record, p.authorID, "community organisation",
		pgToUUID(existing.ID), uuid.Nil, params, changed, changesJSON,
		func(ctx context.Context, fn func(CommunityOrgTxStore) error) error { return p.store.WithTx(ctx, fn) },
		CommunityOrgTxStore.UpdateCommunityOrganisationIntel)
}

