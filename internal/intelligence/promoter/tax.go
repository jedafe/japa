// buildTaxCreateParams maps a validated extraction to a
// CreateTaxObligationGuideIntelParams. OriginSpaceID and DestinationSpaceID
// are resolved by the caller (taxCreatePath) via GetCountrySpace and
// overridden after construction. GuideID is left NULL (Approach B: Studio
// generates the contents guide from the extraction data via intel_record_id,
// ADR-076 Amendment 1).
func buildTaxCreateParams(record gen.IntelRecord, ext extractor.Extraction) gen.CreateTaxObligationGuideIntelParams {
	employmentStatus := stringField(ext, "employment_status")
	if employmentStatus == "" {
		employmentStatus = "other" // satisfy NOT NULL when the extractor omitted it
	}

	return gen.CreateTaxObligationGuideIntelParams{

		OriginSpaceID:        pgtype.UUID{}, // resolved by taxCreatePath
		DestinationSpaceID:   pgtype.UUID{}, // resolved by taxCreatePath
		EmploymentStatus:     employmentStatus,
		ResidencyTrigger:     stringPtrField(ext, "residency_trigger"),
		WorldwideIncomeTaxed: boolPtrField(ext, "worldwide_income_taxed"),
		FirstYearObligations: stringPtrField(ext, "first_year_obligations"),
		ActionChecklist:      jsonbField(ext, "action_checklist"),
		Status:               "published",
		IsActive:             true,
		IntelRecordID:        record.ID,
		GuideID:              pgtype.UUID{}, // NULL — Studio generates the contents guide
		ConfidenceOverall:    record.ConfidenceOverall,
		// spec §530: create path stamps 'verified' + 'ingestion'. The
		// tax_obligation_guides CHECK constraint only allows
		// verification_status IN ('verified','needs_review','conflict','stale')
		// and override_source IN ('ingestion','editorial','mixed').
		VerificationStatus: "verified",
		FreshnessScore:     freshScore,
		OverrideSource:     "ingestion",
		EditorialOverrides: emptyJSONObject(),
	}
}

// buildTaxUpdateParams produces an UpdateTaxObligationGuideIntelParams seeded
// from the existing row, then applies each extraction field that is NOT in
// overrides and whose value actually changed. It returns the params and the
// list of changed column names. Fields in editorial_overrides keep the
// existing value (human edit wins).
//
// origin_space_id and destination_space_id are immutable on the update path
// (the UpdateTaxObligationGuideIntel query does not touch them), so the
// country extraction is only honored on the create path.
func buildTaxUpdateParams(existing gen.TaxObligationGuide, ext extractor.Extraction, overrides map[string]struct{}) (gen.UpdateTaxObligationGuideIntelParams, []string) {
	params := gen.UpdateTaxObligationGuideIntelParams{

		ID:                   existing.ID,
		EmploymentStatus:     existing.EmploymentStatus,
		ResidencyTrigger:     existing.ResidencyTrigger,
		WorldwideIncomeTaxed: existing.WorldwideIncomeTaxed,
		FirstYearObligations: existing.FirstYearObligations,
		ActionChecklist:      existing.ActionChecklist,
		Status:               existing.Status,
		IsActive:             existing.IsActive,
		ConfidenceOverall:    existing.ConfidenceOverall,
		VerificationStatus:   existing.VerificationStatus,
		FreshnessScore:       existing.FreshnessScore,
		OverrideSource:       existing.OverrideSource,
		EditorialOverrides:   existing.EditorialOverrides,
	}

	var changed []string

	// employment_status
	applyStrField(overrides, ext, "employment_status", &params.EmploymentStatus, existing.EmploymentStatus, &changed)
	// residency_trigger
	applyStrPtrField(overrides, ext, "residency_trigger", &params.ResidencyTrigger, existing.ResidencyTrigger, &changed)
	// worldwide_income_taxed
	applyBoolPtrField(overrides, "worldwide_income_taxed", func() *bool { return boolPtrField(ext, "worldwide_income_taxed") }, &params.WorldwideIncomeTaxed, existing.WorldwideIncomeTaxed, &changed)
	// first_year_obligations
	applyStrPtrField(overrides, ext, "first_year_obligations", &params.FirstYearObligations, existing.FirstYearObligations, &changed)
	// action_checklist
	applyJSONField(overrides, ext, "action_checklist", &params.ActionChecklist, existing.ActionChecklist, &changed)

	return params, changed
}

