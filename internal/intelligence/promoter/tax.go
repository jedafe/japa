// boolPtrField returns a *bool extracted from the given extraction field, or
// nil when the field is absent or not a boolean. Used for
// worldwide_income_taxed, which is nullable in the projection table.
func boolPtrField(ext extractor.Extraction, key string) *bool {
	f, ok := ext[key]
	if !ok || f.Value == nil {
		return nil
	}

	switch v := f.Value.(type) {
	case bool:
		return &v
	case string:
		switch v {
		case "true", "True", "TRUE", "1":
			b := true
			return &b
		case "false", "False", "FALSE", "0":
			b := false
			return &b
		}
	case float64:
		b := v != 0
		return &b
	}

	return nil
}

// boolPtrEqual reports whether two *bool values are equal (nil-safe).
func boolPtrEqual(a, b *bool) bool {
	if a == nil || b == nil {
		return a == nil && b == nil
	}

	return *a == *b
}

// derefBool returns the dereferenced bool value, or nil when the pointer is
// nil. Used for the intel_review_log field-change snapshot.
func derefBool(b *bool) any {
	if b == nil {
		return nil
	}

	return *b
}
