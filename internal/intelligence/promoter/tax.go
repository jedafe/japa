// TaxStore is the persistence surface the TaxPromoter needs.
// *stores.Store satisfies this interface; tests substitute a mock.
//
// The tax domain writes a tax_obligation_guides standalone projection row
// (via CreateTaxObligationGuideIntel/UpdateTaxObligationGuideIntel) and
// flips the intel record to 'extracted' status. The contents guide row is
// NO LONGER created here — Studio generates it from the extraction data via
// intel_record_id (ADR-076 Amendment 1). WithTx runs the multi-table writes
// atomically (BUG-01/02 fix, §6.2 transaction boundary).
type TaxStore interface {
	PersonaResolver
	GetIntelRecord(ctx context.Context, id pgtype.UUID) (gen.IntelRecord, error)
	GetIntelSource(ctx context.Context, id pgtype.UUID) (gen.IntelSource, error)
	GetTaxObligationGuideByIntelRecord(ctx context.Context, intelRecordID pgtype.UUID) (gen.TaxObligationGuide, error)
	CreateTaxObligationGuideIntel(ctx context.Context, arg gen.CreateTaxObligationGuideIntelParams) (gen.TaxObligationGuide, error)
	UpdateTaxObligationGuideIntel(ctx context.Context, arg gen.UpdateTaxObligationGuideIntelParams) error
	UpdateIntelRecordStatus(ctx context.Context, arg gen.UpdateIntelRecordStatusParams) error
	CreateIntelReviewLog(ctx context.Context, arg gen.CreateIntelReviewLogParams) error
	// GetCountrySpace resolves the country-level geo space (§05) id for an
	// ISO-3 country code, so the promoter can stamp
	// tax_obligation_guides.origin_space_id and destination_space_id.
	// Returns (pgtype.UUID{}, nil) when no country space exists yet.
	// BUG-005 fix (spec §455).
	GetCountrySpace(ctx context.Context, countryCode string) (pgtype.UUID, error)
	WithTx(ctx context.Context, fn func(TaxTxStore) error) error
}

// TaxTxStore is the subset of TaxStore needed inside a transaction. It
// exposes only the write methods that createPath and updatePath call, so the
// transactional store can be a narrower type. *stores.Store satisfies this
// interface (via WithTx's callback), and the test mock satisfies it directly.
type TaxTxStore interface {
	CreateTaxObligationGuideIntel(ctx context.Context, arg gen.CreateTaxObligationGuideIntelParams) (gen.TaxObligationGuide, error)
	UpdateIntelRecordStatus(ctx context.Context, arg gen.UpdateIntelRecordStatusParams) error
	UpdateTaxObligationGuideIntel(ctx context.Context, arg gen.UpdateTaxObligationGuideIntelParams) error
	CreateIntelReviewLog(ctx context.Context, arg gen.CreateIntelReviewLogParams) error
}

// TaxPromoter promotes tax_obligation_guide intel_records into the
// tax_obligation_guides projection table. It implements the
// editorial-override-respect invariant: on the update path, any field present
// in tax_obligation_guides.editorial_overrides is left untouched so a human
// edit always wins over a re-crawl. The contents guide row is generated by
// Studio from the extraction data (ADR-076 Amendment 1).
type TaxPromoter struct {
	store    TaxStore
	authorID pgtype.UUID // system/automation user credited as the guide author
	aiModel  *string     // AI model used for extraction (ADR-088, INTEL-003)
	now      func() time.Time
}

// TaxPromoterOption configures a TaxPromoter.
type TaxPromoterOption func(*TaxPromoter)

// WithTaxClock overrides the clock used for publish timestamps (tests).
func WithTaxClock(fn func() time.Time) TaxPromoterOption {
	return func(p *TaxPromoter) { p.now = fn }
}

// WithTaxAIModel sets the AI model name stamped on created content rows (ADR-088).
func WithTaxAIModel(model string) TaxPromoterOption {
	return func(p *TaxPromoter) { p.aiModel = &model }
}

// NewTaxPromoter creates a promoter backed by the given store. The ID
// and authorID identify the tenant and system author stamped onto the
// tax_obligation_guides projection rows created by the create path.
func NewTaxPromoter(store TaxStore, authorID pgtype.UUID, opts ...TaxPromoterOption) *TaxPromoter {
	p := &TaxPromoter{store: store, authorID: authorID, aiModel: ptr("gpt-4o-mini"), now: time.Now}
	for _, opt := range opts {
		opt(p)
	}

	return p
}

// Entity returns the entity_type this promoter handles.
func (p *TaxPromoter) Entity() string { return "tax_obligation_guide" }

// ErrNotTax is returned when Promote is called on an intel record whose
// entity_type is not "tax_obligation_guide".
var ErrNotTax = errors.New("promoter: intel record is not a tax_obligation_guide")

// Promote maps the intel record identified by recordID to a
// tax_obligation_guides projection row, creating it or updating it in place
// while respecting editorial overrides.
func (p *TaxPromoter) Promote(ctx context.Context, recordID uuid.UUID) (PromoteResult, error) {
	return promoteDomain(ctx, p.store, recordID, domainPromoteOps[gen.TaxObligationGuide]{
		entityType: p.Entity(),
		notErr:     ErrNotTax,
		loadLabel:  "tax obligation guide",
		getExisting: func(ctx context.Context, pgID pgtype.UUID) (gen.TaxObligationGuide, error) {
			return p.store.GetTaxObligationGuideByIntelRecord(ctx, pgID)
		},
		createPath: p.taxCreatePath,
		updatePath: p.taxUpdatePath,
	})
}

// taxCreatePath inserts the tax_obligation_guides projection row and flips
// the intel record to 'extracted' status. The contents guide row is NO LONGER
// created here — Studio generates it from the extraction data via
// intel_record_id (ADR-076 Amendment 1). Both writes run inside a single
// transaction so a failure in either rolls back the other (BUG-01 fix, §6.2).
//
// Both origin_space_id and destination_space_id are NOT NULL in the schema,
// so when either country space cannot be resolved the record is routed back
// to review rather than failing the promotion. BUG-005 fix (spec §455).
func (p *TaxPromoter) taxCreatePath(ctx context.Context, record gen.IntelRecord, _ gen.IntelSource, ext extractor.Extraction) (PromoteResult, error) {
	// Resolve the origin country's geo space (§05). tax_obligation_guides
	// .origin_space_id is NOT NULL, so when no country space can be resolved
	// we route the record back to review.
	originCountryCode := firstCountry(ext, "origin_country")

	var originSpaceID pgtype.UUID

	if originCountryCode != "" {
		if id, err := p.store.GetCountrySpace(ctx, originCountryCode); err == nil && id.Valid {
			originSpaceID = id
		}
	}

	if !originSpaceID.Valid {
		return PromoteResult{}, fmt.Errorf(
			"promoter: tax obligation guide requires an origin country space but none resolved for %q — routing to review",
			originCountryCode,
		)
	}

	// Resolve the destination country's geo space (§05).
	// tax_obligation_guides.destination_space_id is NOT NULL, so when no
	// country space can be resolved we route the record back to review.
	destinationCountryCode := firstCountry(ext, "country")

	var destinationSpaceID pgtype.UUID

	if destinationCountryCode != "" {
		if id, err := p.store.GetCountrySpace(ctx, destinationCountryCode); err == nil && id.Valid {
			destinationSpaceID = id
		}
	}

	if !destinationSpaceID.Valid {
		return PromoteResult{}, fmt.Errorf(
			"promoter: tax obligation guide requires a destination country space but none resolved for %q — routing to review",
			destinationCountryCode,
		)
	}

	taxParams := buildTaxCreateParams(record, ext)
	taxParams.OriginSpaceID = originSpaceID
	taxParams.DestinationSpaceID = destinationSpaceID

	var result PromoteResult

	err := p.store.WithTx(ctx, func(tx TaxTxStore) error {
		guide, err := tx.CreateTaxObligationGuideIntel(ctx, taxParams)
		if err != nil {
			return fmt.Errorf("promoter: create tax obligation guide: %w", err)
		}

		if err := tx.UpdateIntelRecordStatus(ctx, gen.UpdateIntelRecordStatusParams{
			ID:     record.ID,
			Status: "extracted",
		}); err != nil {
			return fmt.Errorf("promoter: mark intel record extracted: %w", err)
		}

		result = PromoteResult{
			DomainID:  pgToUUID(guide.ID),
			ContentID: uuid.Nil,
			Action:    ActionCreated,
		}

		return nil
	})

	return result, err
}

// taxUpdatePath applies the new extraction to the existing
// tax_obligation_guides row, skipping any field present in
// editorial_overrides, and records an auto_update review-log entry when
// fields actually change. The tax update and the review log write run inside
// a single transaction so the audit trail is always consistent with the
// projection state (BUG-02 fix, §6.2).
//
// origin_space_id and destination_space_id are immutable on the update path
// (the UpdateTaxObligationGuideIntel query does not touch them), so the
// country extraction is only honored on the create path.
func (p *TaxPromoter) taxUpdatePath(ctx context.Context, record gen.IntelRecord, existing gen.TaxObligationGuide, ext extractor.Extraction) (PromoteResult, error) {
	overrides, err := parseOverrideKeys(existing.EditorialOverrides)
	if err != nil {
		return PromoteResult{}, fmt.Errorf("promoter: parse editorial overrides: %w", err)
	}

	params, changed := buildTaxUpdateParams(existing, ext, overrides)
	params.FreshnessScore = freshScore

	var changesJSON []byte

	if len(changed) > 0 {
		if changesJSON, err = marshalTaxFieldChanges(existing, params, changed); err != nil {
			return PromoteResult{}, fmt.Errorf("promoter: marshal field changes: %w", err)
		}
	}

	return domainUpdateTx(ctx, record, p.authorID, "tax obligation guide",
		pgToUUID(existing.ID), uuid.Nil, params, changed, changesJSON,
		func(ctx context.Context, fn func(TaxTxStore) error) error { return p.store.WithTx(ctx, fn) },
		TaxTxStore.UpdateTaxObligationGuideIntel)
}

