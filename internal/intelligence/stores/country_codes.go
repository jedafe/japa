// countryCodeCandidates returns the ordered ISO 3166-1 alpha-2 candidates to
// try against spaces.geo_code for an extracted country value. Handles
// alpha-2 input directly, alpha-3 via the iso3ToISO2 map, and common
// aliases ("UK" → "GB").
func countryCodeCandidates(raw string) []string {
	upper := strings.ToUpper(raw)
	var out []string
	add := func(c string) {
		for _, e := range out {
			if e == c {
				return
			}
		}
		out = append(out, c)
	}
	if len(upper) == 2 {
		add(upper)
	}
	if len(upper) == 3 {
		if c, ok := iso3ToISO2[upper]; ok {
			add(c)
		}
	}
	if c, ok := countryCodeAliases[upper]; ok {
		add(c)
	}
	return out
}

// countryNameCandidate returns the canonical seeded space name for an
// extracted country value, resolving common alternate spellings.
func countryNameCandidate(raw string) string {
	trimmed := strings.TrimSpace(raw)
	if canonical, ok := countryNameAliases[strings.ToLower(trimmed)]; ok {
		return canonical
	}
	return trimmed
}
