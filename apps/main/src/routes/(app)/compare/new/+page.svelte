<script lang="ts">
	import { t } from '$lib/i18n';
	import { page } from '$app/state';
	import { enhance } from '$app/forms';
	import { GitCompare, Plus, Loader2, ArrowRight, ArrowLeft, Check, X, Sparkles } from 'lucide-svelte';
	import type { ActionData, PageData } from './$types';

	let { data, form }: { data: PageData; form: ActionData } = $props();

	const spaces = $derived(data.spaces);

	// Multi-step state (Phase 16.04).
	let step = $state(1);
	const TOTAL_STEPS = 3;

	let title = $state('');
	let body = $state('');
	let visibility = $state<'public' | 'unlisted' | 'private'>('public');
	let spaceId = $state('');
	let submitting = $state(false);

	// Step 2 — items to compare.
	let items = $state<{ name: string; slug: string }[]>([{ name: '', slug: '' }, { name: '', slug: '' }]);
	let itemError = $state('');

	// Step 3 — dimensions (auto-generated, editable).
	let dimensions = $state<string[]>([]);
	let generating = $state(false);

	const pageTitle = $derived(t('compare.new.title', 'New comparison — JapaConnect'));
	const description = $derived(
		t('compare.new.description', 'Create a new comparison to evaluate items across dimensions.')
	);

	const inputClass =
		'w-full rounded-[var(--radius)] border border-[var(--color-border)] bg-[var(--color-surface)] px-3 py-2 text-sm text-[var(--color-text)] outline-none focus:border-[var(--color-primary)]';

	const canProceedStep1 = $derived(title.trim().length > 0);
	const canProceedStep2 = $derived(items.filter((i) => i.name.trim()).length >= 2);

	function addItem() {
		items = [...items, { name: '', slug: '' }];
	}
	function removeItem(idx: number) {
		items = items.filter((_, i) => i !== idx);
		if (items.length < 2) items = [{ name: '', slug: '' }, { name: '', slug: '' }];
	}
	function updateItem(idx: number, name: string) {
		const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 80);
		items = items.map((it, i) => (i === idx ? { name, slug } : it));
	}

	function nextStep() {
		if (step === 1 && !canProceedStep1) return;
		if (step === 2 && !canProceedStep2) {
			itemError = t('compare.new.items_min', 'At least 2 items are required');
			return;
		}
		itemError = '';
		step = Math.min(step + 1, TOTAL_STEPS);
		if (step === 3 && dimensions.length === 0) {
			autoGenerateDimensions();
		}
	}
	function prevStep() {
		step = Math.max(step - 1, 1);
	}

	// Phase 16.05 — AI-assisted dimension auto-generation.
	// Best-effort: calls POST /comparisons/auto-dimensions with the item names.
	// Falls back to a sensible default set on failure.
	async function autoGenerateDimensions() {
		generating = true;
		try {
			const res = await fetch('/api/v1/comparisons/auto-dimensions', {
				method: 'POST',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify({ items: items.map((i) => i.name).filter(Boolean) })
			});
			if (res.ok) {
				const data = await res.json();
				dimensions = data.dimensions ?? data.data?.dimensions ?? [];
			}
		} catch {
			// fall through to defaults
		}
		if (dimensions.length === 0) {
			dimensions = [
				t('compare.dimension.price', 'Price'),
				t('compare.dimension.quality', 'Quality'),
				t('compare.dimension.features', 'Features'),
				t('compare.dimension.rating', 'Overall rating')
			];
		}
		generating = false;
	}

	function addDimension() {
		dimensions = [...dimensions, ''];
	}
	function removeDimension(idx: number) {
		dimensions = dimensions.filter((_, i) => i !== idx);
	}
	function updateDimension(idx: number, value: string) {
		dimensions = dimensions.map((d, i) => (i === idx ? value : d));
	}
</script>

<svelte:head>
	<title>{pageTitle}</title>
	<meta name="description" content={description} />
	<meta property="og:title" content={pageTitle} />
	<meta property="og:description" content={description} />
	<meta property="og:type" content="website" />
	<meta property="og:url" content={page.url.href} />
</svelte:head>

<div class="mx-auto w-full max-w-2xl">
	<!-- Header -->
	<div class="border-b border-[var(--color-border)] px-4 py-3">
		<h1 class="flex items-center gap-2 text-lg font-semibold text-[var(--color-text)]">
			<GitCompare size={20} /> {t('compare.new.heading', 'New comparison')}
		</h1>
		<p class="mt-1 text-sm text-[var(--color-text-subtle)]">
			{t('compare.new.subtitle', 'Create a comparison to evaluate items across dimensions.')}
		</p>
	</div>

	<!-- Step indicator (Phase 16.04) -->
	<div class="flex items-center gap-2 px-4 py-3">
		{#each Array(TOTAL_STEPS) as _, i (i)}
			<div class="flex items-center gap-2">
				{#if i > 0}
					<div class="h-px w-8 {step > i ? 'bg-[var(--color-primary)]' : 'bg-[var(--color-border)]'}"></div>
				{/if}
				<div
					class="grid h-7 w-7 shrink-0 place-items-center rounded-full text-xs font-medium transition-colors {step > i + 1
						? 'bg-[var(--color-primary)] text-[var(--color-primary-contrast)]'
						: step === i + 1
							? 'border-2 border-[var(--color-primary)] text-[var(--color-primary)]'
							: 'border border-[var(--color-border)] text-[var(--color-muted)]'}"
				>
					{#if step > i + 1}
						<Check size={14} />
					{:else}
						{i + 1}
					{/if}
				</div>
			</div>
		{/each}
	</div>

	<div class="p-3">
		{#if form?.message}
			<div
				class="mb-4 rounded-[var(--radius)] border border-[var(--color-border)] bg-[var(--color-surface-subtle)] px-3 py-2 text-sm text-[var(--color-text-subtle)]"
			>
				{form.message}
			</div>
		{/if}

		<form
			method="POST"
			use:enhance={() => {
				submitting = true;
				return async ({ update }) => {
					await update();
					submitting = false;
				};
			}}
			class="rounded-[var(--radius-card)] border border-[var(--color-border)] bg-[var(--color-surface)] p-4"
		>
			<!-- Hidden fields carry all step data on final submit -->
			<input type="hidden" name="title" value={title} />
			<input type="hidden" name="body" value={body} />
			<input type="hidden" name="visibility" value={visibility} />
			<input type="hidden" name="space_id" value={spaceId} />
			{#each items as item, i (i)}
				{#if item.name.trim()}
					<input type="hidden" name="item_name[]" value={item.name} />
					<input type="hidden" name="item_slug[]" value={item.slug} />
				{/if}
			{/each}
			{#each dimensions as dim, i (i)}
				{#if dim.trim()}
					<input type="hidden" name="dimension[]" value={dim} />
				{/if}
			{/each}

			{#if step === 1}
				<!-- Step 1: Details -->
				<div class="space-y-4">
					<h2 class="text-sm font-medium text-[var(--color-text)]">
						{t('compare.new.step1', 'Comparison details')}
					</h2>
					<div>
						<label for="title" class="mb-1 block text-sm font-medium text-[var(--color-text)]">
							{t('compare.new.field_title', 'Title')}
						</label>
						<input
							id="title"
							type="text"
							required
							bind:value={title}
							placeholder={t('compare.new.title_placeholder', 'Comparison title')}
							class={inputClass}
						/>
					</div>
					<div>
						<label for="body" class="mb-1 block text-sm font-medium text-[var(--color-text)]">
							{t('compare.new.field_body', 'Description')}
						</label>
						<textarea
							id="body"
							rows="3"
							bind:value={body}
							placeholder={t('compare.new.body_placeholder', 'Describe what this comparison is about…')}
							class={inputClass}
						></textarea>
					</div>
					<div class="grid gap-4 sm:grid-cols-2">
						<div>
							<label for="visibility" class="mb-1 block text-sm font-medium text-[var(--color-text)]">
								{t('compare.new.field_visibility', 'Visibility')}
							</label>
							<select id="visibility" bind:value={visibility} class={inputClass}>
								<option value="public">{t('compare.new.visibility_public', 'Public')}</option>
								<option value="unlisted">{t('compare.new.visibility_unlisted', 'Unlisted')}</option>
								<option value="private">{t('compare.new.visibility_private', 'Private')}</option>
							</select>
						</div>
						<div>
							<label for="space_id" class="mb-1 block text-sm font-medium text-[var(--color-text)]">
								{t('compare.new.field_space', 'Space')}
							</label>
							<select id="space_id" bind:value={spaceId} class={inputClass}>
								<option value="">{t('compare.new.space_none', 'No space')}</option>
								{#each spaces as space (space.id)}
									<option value={space.id}>{space.name}</option>
								{/each}
							</select>
						</div>
					</div>
				</div>
			{:else if step === 2}
				<!-- Step 2: Add items -->
				<div class="space-y-4">
					<h2 class="text-sm font-medium text-[var(--color-text)]">
						{t('compare.new.step2', 'Add items to compare')}
					</h2>
					<p class="text-xs text-[var(--color-muted)]">
						{t('compare.new.step2_hint', 'Add at least 2 items. You can add more later.')}
					</p>
					{#if itemError}
						<p class="text-sm text-red-500" role="alert">{itemError}</p>
					{/if}
					<div class="space-y-2">
						{#each items as item, i (i)}
							<div class="flex items-center gap-2">
								<input
									type="text"
									value={item.name}
									oninput={(e) => updateItem(i, e.currentTarget.value)}
									placeholder={t('compare.new.item_placeholder', 'Item {n}').replace('{n}', String(i + 1))}
									class={inputClass}
								/>
								<button
									type="button"
									onclick={() => removeItem(i)}
									class="shrink-0 rounded p-1.5 text-[var(--color-muted)] hover:bg-red-500/10 hover:text-red-500"
									aria-label={t('common.remove', 'Remove')}
								>
									<X size={16} />
								</button>
							</div>
						{/each}
					</div>
					<button
						type="button"
						onclick={addItem}
						class="inline-flex items-center gap-1 text-sm text-[var(--color-primary)] hover:underline"
					>
						<Plus size={14} /> {t('compare.new.add_item', 'Add another item')}
					</button>
				</div>
			{:else if step === 3}
				<!-- Step 3: Dimensions (auto-generated, editable) -->
				<div class="space-y-4">
					<h2 class="flex items-center gap-2 text-sm font-medium text-[var(--color-text)]">
						<Sparkles size={15} />
						{t('compare.new.step3', 'Comparison dimensions')}
					</h2>
					<p class="text-xs text-[var(--color-muted)]">
						{t('compare.new.step3_hint', 'Dimensions were auto-generated. Edit or add your own.')}
					</p>
					{#if generating}
						<div class="flex items-center gap-2 text-sm text-[var(--color-muted)]">
							<Loader2 size={15} class="animate-spin" />
							{t('compare.new.generating', 'Generating dimensions…')}
						</div>
					{:else}
						<div class="space-y-2">
							{#each dimensions as dim, i (i)}
								<div class="flex items-center gap-2">
									<input
										type="text"
										value={dim}
										oninput={(e) => updateDimension(i, e.currentTarget.value)}
										placeholder={t('compare.new.dimension_placeholder', 'Dimension name')}
										class={inputClass}
									/>
									<button
										type="button"
										onclick={() => removeDimension(i)}
										class="shrink-0 rounded p-1.5 text-[var(--color-muted)] hover:bg-red-500/10 hover:text-red-500"
										aria-label={t('common.remove', 'Remove')}
									>
										<X size={16} />
									</button>
								</div>
							{/each}
						</div>
						<button
							type="button"
							onclick={addDimension}
							class="inline-flex items-center gap-1 text-sm text-[var(--color-primary)] hover:underline"
						>
							<Plus size={14} /> {t('compare.new.add_dimension', 'Add dimension')}
						</button>
					{/if}
				</div>
			{/if}

			<!-- Navigation buttons -->
			<div class="mt-6 flex items-center justify-between border-t border-[var(--color-border)] pt-4">
				{#if step > 1}
					<button
						type="button"
						onclick={prevStep}
						class="inline-flex items-center gap-1.5 rounded-[var(--radius)] border border-[var(--color-border)] px-4 py-2 text-sm font-medium text-[var(--color-text)] transition-colors hover:bg-[var(--color-surface-subtle)]"
					>
						<ArrowLeft size={16} /> {t('common.back', 'Back')}
					</button>
				{:else}
					<span></span>
				{/if}

				{#if step < TOTAL_STEPS}
					<button
						type="button"
						onclick={nextStep}
						disabled={(step === 1 && !canProceedStep1) || (step === 2 && !canProceedStep2)}
						class="inline-flex items-center gap-1.5 rounded-[var(--radius)] bg-[var(--color-primary)] px-4 py-2 text-sm font-medium text-[var(--color-primary-contrast)] transition-colors hover:bg-[var(--color-primary-hover)] disabled:opacity-50"
					>
						{t('common.next', 'Next')} <ArrowRight size={16} />
					</button>
				{:else}
					<button
						type="submit"
						disabled={submitting || generating}
						class="inline-flex items-center gap-1.5 rounded-[var(--radius)] bg-[var(--color-primary)] px-4 py-2 text-sm font-medium text-[var(--color-primary-contrast)] transition-colors hover:bg-[var(--color-primary-hover)] disabled:opacity-50"
					>
						{#if submitting}
							<Loader2 size={16} class="animate-spin" />
						{:else}
							<Plus size={16} />
						{/if}
						{t('compare.new.submit', 'Create comparison')}
					</button>
				{/if}
			</div>
		</form>
	</div>
</div>
