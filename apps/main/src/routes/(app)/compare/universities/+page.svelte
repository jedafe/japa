<script lang="ts">
	import { t } from '$lib/i18n';
	import { page } from '$app/state';
	import { enhance } from '$app/forms';
	import { untrack } from 'svelte';
	import { GraduationCap, GitCompare, Plus, X, Check, Loader2, ArrowLeft, Search, Sparkles } from 'lucide-svelte';
	import { EmptyState } from '$lib/components/ui';
	import { autoGenerateDimensions as autoGenerateDimensionsApi } from '$lib/api/create';
	import type { University } from '$lib/types';
	import type { ActionData, PageData } from './$types';

	let { data, form }: { data: PageData; form: ActionData } = $props();

	const universities = $derived<University[]>(data.universities);
	const universityTypeId = $derived(data.universityTypeId);

	// Restore form values after a server-side validation failure (the action
	// returns `values` via fail()). Falls back to query-param pre-fill for
	// the initial load (Section 39 university "Compare" button).
	const v = untrack(() => form?.values);
	let title = $state(v?.title ?? '');
	let visibility = $state<'public' | 'unlisted' | 'private'>(
		(v?.visibility as 'public' | 'unlisted' | 'private') ?? 'public'
	);
	let submitting = $state(false);

	// Selected universities (2–4). Pre-fill item 1 from the query param.
	const MAX_ITEMS = 4;
	let selected = $state<University[]>(
		untrack(() => (data.item1 ? [data.item1] : []))
	);
	let query = $state('');

	const filtered = $derived.by(() => {
		const q = query.trim().toLowerCase();
		if (!q) return universities;
		return universities.filter((u) => u.name.toLowerCase().includes(q));
	});

	// Auto-generate comparison dimensions heuristically from the selected
	// university names (POST /jce/comparisons/auto-dimensions — Section 30, no AI
	// tokens). The universities comparison type's field group is seeded empty
	// (field_count=0), so the backend cannot auto-derive dimensions from the
	// type; we must supply them explicitly, same as the /compare/new wizard.
	// Re-runs only when the set of selected names actually changes.
	let dimensions = $state<string[]>([]);
	let generating = $state(false);
	let dimError = $state('');
	let lastGeneratedKey = $state('');
	$effect(() => {
		const names = selected.map((s) => s.name);
		if (names.length < 2) {
			dimensions = [];
			lastGeneratedKey = '';
			return;
		}
		const key = names.join('|');
		if (key === lastGeneratedKey) return;
		lastGeneratedKey = key;
		autoGenerateDimensions(names);
	});
	async function autoGenerateDimensions(names: string[]) {
		generating = true;
		dimError = '';
		const res = await autoGenerateDimensionsApi(names);
		if (res.data) {
			dimensions = res.data.dimensions ?? [];
		} else if (res.error) {
			dimError = res.error.message;
		} else {
			dimError = t('compare.new.generating_failed', 'Could not generate dimensions. Add them manually.');
		}
		generating = false;
	}
	function addDimension() {
		dimensions = [...dimensions, ''];
	}
	function removeDimension(idx: number) {
		dimensions = dimensions.filter((_, i) => i !== idx);
	}
	function updateDimension(idx: number, value: string) {
		dimensions = dimensions.map((d, i) => (i === idx ? value : d));
	}

	const isSelected = (uni: University) => selected.some((s) => s.id === uni.id);
	const canSelectMore = $derived(selected.length < MAX_ITEMS);
	const canSubmit = $derived(title.trim().length > 0 && selected.length >= 2 && dimensions.length > 0);

	function toggle(uni: University) {
		if (isSelected(uni)) {
			selected = selected.filter((s) => s.id !== uni.id);
		} else if (canSelectMore) {
			selected = [...selected, uni];
		}
	}
	function removeSelected(uni: University) {
		selected = selected.filter((s) => s.id !== uni.id);
	}

	// Default comparison title derived from the selected universities, but
	// only when the user hasn't typed their own — avoids clobbering edits.
	let lastAutoTitle = $state('');
	$effect(() => {
		if (title && title === lastAutoTitle) {
			// user is still on the auto title; refresh it as selection changes
		} else if (title) {
			return; // user typed their own — leave it alone
		}
		const names = selected.map((s) => s.name);
		const auto =
			names.length === 0
				? ''
				: names.length === 1
					? t('compare.universities.title_one', 'Compare {a}').replace('{a}', names[0])
					: t('compare.universities.title_many', 'Comparing {names}').replace(
							'{names}',
							names.join(' vs ')
						);
		lastAutoTitle = auto;
		title = auto;
	});

	const pageTitle = $derived(t('compare.universities.page_title', 'Compare universities — JapaConnect'));
	const description = $derived(
		t('compare.universities.description', 'Pick 2–4 universities to compare side by side.')
	);

	const inputClass =
		'w-full rounded-[var(--radius)] border border-[var(--color-border)] bg-[var(--color-surface)] px-3 py-2 text-sm text-[var(--color-text)] outline-none focus:border-[var(--color-primary)]';
</script>

<svelte:head>
	<title>{pageTitle}</title>
	<meta name="description" content={description} />
	<meta property="og:title" content={pageTitle} />
	<meta property="og:description" content={description} />
	<meta property="og:type" content="website" />
	<meta property="og:url" content={page.url.href} />
</svelte:head>

<div class="mx-auto w-full max-w-full">
	<!-- Header -->
	<div class="border-b border-[var(--color-border)] px-4 py-3">
		<a
			href="/compare"
			class="mb-1 inline-flex items-center gap-1.5 text-sm text-[var(--color-text-subtle)] transition-colors hover:text-[var(--color-text)]"
		>
			<ArrowLeft size={15} /> {t('compare.back', 'Back to compare')}
		</a>
		<h1 class="flex items-center gap-2 text-lg font-semibold text-[var(--color-text)]">
			<GitCompare size={20} /> {t('compare.universities.heading', 'Compare universities')}
		</h1>
		<p class="mt-1 text-sm text-[var(--color-text-subtle)]">{description}</p>
	</div>

	<div class="p-3">
		{#if form?.message}
			<div
				class="mb-4 rounded-[var(--radius)] border border-red-500/30 bg-red-500/5 px-3 py-2 text-sm text-red-500"
				role="alert"
			>
				{form.message}
			</div>
		{/if}

		<form
			method="POST"
			use:enhance={() => {
				submitting = true;
				return async ({ update }) => {
					await update();
					submitting = false;
				};
			}}
			class="rounded-[var(--radius-card)] border border-[var(--color-border)] bg-[var(--color-surface)] p-4"
		>
			<!-- Hidden fields -->
			<input type="hidden" name="title" value={title} />
			<input type="hidden" name="visibility" value={visibility} />
			<input type="hidden" name="type_id" value={universityTypeId} />
			{#if selected[0]}
				<input type="hidden" name="space_id" value={selected[0].id} />
			{/if}
			{#each selected as uni (uni.id)}
				<input type="hidden" name="item_name[]" value={uni.name} />
				<input
					type="hidden"
					name="item_ref[]"
					value={JSON.stringify({ type: 'space', id: uni.id })}
				/>
			{/each}
			{#each dimensions as dim, i (i)}
				{#if dim.trim()}
					<input type="hidden" name="dimension[]" value={dim} />
				{/if}
			{/each}

			<!-- Title + visibility -->
			<div class="grid gap-4 sm:grid-cols-[1fr_auto]">
				<div>
					<label for="title" class="mb-1 block text-sm font-medium text-[var(--color-text)]">
						{t('compare.universities.field_title', 'Comparison title')}
					</label>
					<input
						id="title"
						type="text"
						bind:value={title}
						placeholder={t('compare.universities.title_placeholder', 'e.g. Top UK Universities for Engineering')}
						class={inputClass}
					/>
				</div>
				<div>
					<label for="visibility" class="mb-1 block text-sm font-medium text-[var(--color-text)]">
						{t('compare.new.field_visibility', 'Visibility')}
					</label>
					<select id="visibility" bind:value={visibility} class={inputClass}>
						<option value="public">{t('compare.new.visibility_public', 'Public')}</option>
						<option value="unlisted">{t('compare.new.visibility_unlisted', 'Unlisted')}</option>
						<option value="private">{t('compare.new.visibility_private', 'Private')}</option>
					</select>
				</div>
			</div>

			<!-- Selected universities -->
			<div class="mt-4">
				<h2 class="text-sm font-medium text-[var(--color-text)]">
					{t('compare.universities.selected', 'Selected')} ({selected.length}/{MAX_ITEMS})
				</h2>
				<p class="mt-0.5 text-xs text-[var(--color-muted)]">
					{t('compare.select_hint', 'Select 2-4 universities to compare.')}
				</p>
				{#if selected.length === 0}
					<p class="mt-2 text-sm text-[var(--color-muted)]">
						{t('compare.universities.none_selected', 'Pick universities from the list below.')}
					</p>
				{:else}
					<div class="mt-2 flex flex-wrap gap-2">
						{#each selected as uni (uni.id)}
							<span
								class="inline-flex items-center gap-1.5 rounded-full border border-[var(--color-primary)] bg-[var(--color-primary)]/5 px-3 py-1 text-sm text-[var(--color-text)]"
							>
								<GraduationCap size={13} class="text-[var(--color-primary)]" />
								{uni.name}
								<button
									type="button"
									onclick={() => removeSelected(uni)}
									class="rounded-full p-0.5 text-[var(--color-muted)] hover:bg-red-500/10 hover:text-red-500"
									aria-label={t('common.remove', 'Remove')}
								>
									<X size={13} />
								</button>
							</span>
						{/each}
					</div>
				{/if}
			</div>

			<!-- Search + picker -->
			<div class="mt-4">
				<div class="relative">
					<Search size={15} class="pointer-events-none absolute left-3 top-1/2 -translate-y-1/2 text-[var(--color-muted)]" />
					<input
						type="text"
						bind:value={query}
						placeholder={t('compare.universities.search', 'Search universities…')}
						class="{inputClass} pl-9"
						aria-label={t('compare.universities.search', 'Search universities…')}
					/>
				</div>

				{#if universities.length === 0}
					<div class="mt-3">
						<EmptyState
							icon={GraduationCap}
							title={t('compare.no_universities', 'No universities to compare')}
						/>
					</div>
				{:else if filtered.length === 0}
					<div class="mt-3">
						<EmptyState
							icon={Search}
							title={t('compare.universities.no_match', 'No universities match your search')}
						/>
					</div>
				{:else}
					<div class="mt-3 grid max-h-[28rem] gap-2 overflow-y-auto pr-1 sm:grid-cols-2">
						{#each filtered as uni (uni.id)}
							{@const sel = isSelected(uni)}
							<button
								type="button"
								onclick={() => toggle(uni)}
								disabled={!sel && !canSelectMore}
								class="flex items-center gap-3 rounded-[var(--radius)] border p-3 text-left transition-colors {sel
									? 'border-[var(--color-primary)] bg-[var(--color-primary)]/5'
									: 'border-[var(--color-border)] bg-[var(--color-surface)] hover:bg-[var(--color-surface-subtle)] disabled:opacity-40 disabled:hover:bg-[var(--color-surface)]'}"
								aria-pressed={sel}
							>
								<span
									class="grid h-10 w-10 shrink-0 place-items-center rounded-[var(--radius)] bg-[var(--color-surface-subtle)] text-[var(--color-text-subtle)]"
								>
									{#if sel}
										<Check size={18} class="text-[var(--color-primary)]" />
									{:else}
										<GraduationCap size={18} />
									{/if}
								</span>
								<span class="min-w-0 flex-1">
									<span class="block truncate text-sm font-medium text-[var(--color-text)]">{uni.name}</span>
									<span class="mt-0.5 flex flex-wrap items-center gap-3 text-xs text-[var(--color-muted)]">
										{#if uni.geo_code}<span>{uni.geo_code}</span>{/if}
										<span class="inline-flex items-center gap-1">{uni.member_count} {t('compare.members', 'Members')}</span>
									</span>
								</span>
							</button>
						{/each}
					</div>
				{/if}
			</div>

			<!-- Dimensions (auto-generated, editable) — Section 30.
			     Auto-generated heuristically from the selected university names
			     via POST /jce/comparisons/auto-dimensions. The user can edit/add/
			     remove before creating. Shown only once 2+ universities are
			     selected. -->
			{#if selected.length >= 2}
				<div class="mt-4 border-t border-[var(--color-border)] pt-4">
					<h2 class="flex items-center gap-2 text-sm font-medium text-[var(--color-text)]">
						<Sparkles size={15} class="text-[var(--color-primary)]" />
						{t('compare.universities.dimensions', 'Comparison dimensions')}
					</h2>
					<p class="mt-0.5 text-xs text-[var(--color-muted)]">
						{t('compare.universities.dimensions_hint', 'Auto-generated — edit or add your own. These become the comparison columns.')}
					</p>
					{#if dimError}
						<p class="mt-2 text-sm text-red-500" role="alert">{dimError}</p>
					{/if}
					{#if generating}
						<div class="mt-2 flex items-center gap-2 text-sm text-[var(--color-muted)]">
							<Loader2 size={15} class="animate-spin" />
							{t('compare.new.generating', 'Generating dimensions…')}
						</div>
					{:else}
						<div class="mt-2 space-y-2">
							{#each dimensions as dim, i (i)}
								<div class="flex items-center gap-2">
									<input
										type="text"
										value={dim}
										oninput={(e) => updateDimension(i, e.currentTarget.value)}
										placeholder={t('compare.new.dimension_placeholder', 'Dimension name')}
										class={inputClass}
									/>
									<button
										type="button"
										onclick={() => removeDimension(i)}
										class="shrink-0 rounded p-1.5 text-[var(--color-muted)] hover:bg-red-500/10 hover:text-red-500"
										aria-label={t('common.remove', 'Remove')}
									>
										<X size={16} />
									</button>
								</div>
							{/each}
						</div>
						<button
							type="button"
							onclick={addDimension}
							class="mt-2 inline-flex items-center gap-1 text-sm text-[var(--color-primary)] hover:underline"
						>
							<Plus size={14} /> {t('compare.new.add_dimension', 'Add dimension')}
						</button>
					{/if}
				</div>
			{/if}

			<!-- Submit -->
			<div class="mt-6 flex items-center justify-between border-t border-[var(--color-border)] pt-4">
				<a
					href="/compare"
					class="inline-flex items-center gap-1.5 rounded-[var(--radius)] border border-[var(--color-border)] px-4 py-2 text-sm font-medium text-[var(--color-text)] transition-colors hover:bg-[var(--color-surface-subtle)]"
				>
					<ArrowLeft size={16} /> {t('common.cancel', 'Cancel')}
				</a>
				<button
					type="submit"
					disabled={submitting || !canSubmit}
					class="inline-flex items-center gap-1.5 rounded-[var(--radius)] bg-[var(--color-primary)] px-4 py-2 text-sm font-medium text-[var(--color-primary-contrast)] transition-colors hover:bg-[var(--color-primary-hover)] disabled:opacity-50"
				>
					{#if submitting}
						<Loader2 size={16} class="animate-spin" />
					{:else}
						<Plus size={16} />
					{/if}
					{t('compare.universities.submit', 'Create comparison')}
				</button>
			</div>
		</form>
	</div>
</div>
