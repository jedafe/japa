<script lang="ts">
	import { t } from '$lib/i18n';
	import { untrack } from 'svelte';
	import { Plus, X, AlertCircle, Table as TableIcon, ChevronDown } from 'lucide-svelte';
	import PostEditor, { type EditorMode } from './PostEditor.svelte';
	import {
		addComparisonItem,
		addComparisonDimension,
		deleteComparisonItem,
		deleteComparisonDimension,
		patchComparisonItem,
		patchComparisonDimension,
		setDimensionValues,
		autoGenerateDimensions
	} from '$lib/api/create';
	import type { ComparisonItem, ComparisonDimension, ComparisonType } from '$lib/types';

	interface Props {
		/** The composer's content row ID (created via POST /content by ComposerState).
		 *  When null, the composer hasn't created the row yet — onEnsureContent
		 *  is called to trigger a flush. */
		contentId: string | null;
		/** Trigger a composer flush so the content row exists, then return its ID. */
		onEnsureContent: () => Promise<string | null>;
		/** Existing items when restoring a comparison draft (from GET /jce/comparisons/{id}). */
		initialItems?: ComparisonItem[];
		/** Existing dimensions when restoring a comparison draft. */
		initialDimensions?: ComparisonDimension[];
		/** Admin-defined comparison types (Section 30) for the type selector. */
		comparisonTypes?: ComparisonType[];
	/** Valid dimension types from GET /jce/comparisons/dimension-types (Rule 16). */
	dimensionTypes?: { value: string; label: string }[];
		/** Rich-text body HTML (introduction/context above the comparison table). */
		bodyHtml?: string;
		/** Callback when the body HTML changes (drives autosave). */
		onhtml?: (html: string) => void;
		/** Default editor mode (block | wysiwyg | markdown). */
		defaultEditor?: EditorMode;
		/** Notify parent of item/dimension counts (drives the publish gate). */
		oncounts: (items: number, dims: number) => void;
		/** Notify parent that an edit was made (drives autosave). */
		onedit: () => void;
	}

	let {
		contentId,
		onEnsureContent,
		initialItems = [],
		initialDimensions = [],
		comparisonTypes = [],
		dimensionTypes = [],
		bodyHtml = '',
		onhtml,
		defaultEditor = 'block',
		oncounts,
		onedit
	}: Props = $props();

	// Dimension types from the API (GET /jce/comparisons/dimension-types, Rule 16).
	// If the API call failed and the parent passed an empty list, the selector
	// is disabled so no hardcoded fallback data lives in production code.
	const dimensionTypeOptions = $derived(dimensionTypes.map((d) => d.value));
	const dimensionTypesError = $derived(dimensionTypes.length === 0);
	type DimensionType = string;

	// Seed from the draft's existing items/dimensions when provided (e.g.
	// restoring a comparison draft created by the /compare/new wizard).
	let items = $state<{ id: string | null; title: string; description: string }[]>(
		untrack(() => initialItems.map((it) => ({ id: it.id, title: it.title, description: it.description ?? '' })))
	);
	let dimensions = $state<{ id: string | null; label: string; dimension_type: DimensionType }[]>(
		untrack(() =>
			initialDimensions.map((d) => ({
				id: d.id,
				label: d.label,
				dimension_type: (d.dimension_type as DimensionType) ?? 'text'
			}))
		)
	);
	let cells = $state<Record<string, string>>({}); // `${dimIdx}:${itemIdx}` → value

	// Debounce timers for cell-value writes (avoid N api calls per keystroke).
	// Plain variable — timers are not reactive state.
	let valueTimers: Record<string, ReturnType<typeof setTimeout>> = {};

	// Pending operation lock — prevents concurrent ensureContent calls.
	let ensuring = false;

	// User-visible error message (API failures surface here instead of
	// silently breaking the UI).
	let apiError = $state('');

	// Selected comparison type (Section 30 step 1 — "Select Comparison Type").
	// Empty = "General (no type)". When a type is selected, its field group
	// fields can be auto-generated as dimensions.
	let selectedTypeId = $state('');

	$effect(() => oncounts(items.length, dimensions.length));

	function cellKey(dimIdx: number, itemIdx: number) {
		return `${dimIdx}:${itemIdx}`;
	}

	/** Resolve the content row ID, triggering a composer flush if the row
	 *  hasn't been created yet. Returns null on failure. The composer won't
	 *  create the content row until a title is entered (canSave gate), so we
	 *  surface a clear message when that's the blocker. */
	async function ensureContentId(): Promise<string | null> {
		if (contentId) return contentId;
		if (ensuring) return null; // a concurrent ensure is already in flight
		ensuring = true;
		apiError = '';
		const id = await onEnsureContent();
		ensuring = false;
		if (!id) {
			apiError = t('create.comparison.need_title', 'Enter a title first, then add items.');
		}
		return id;
	}

	async function addItem() {
		const id = await ensureContentId();
		if (!id) return;
		apiError = '';
		const res = await addComparisonItem(id, { title: 'New item', description: '', position: items.length });
		if (res.error) {
			apiError = res.error.message;
			return;
		}
		if (res.data) items = [...items, { id: res.data.id, title: 'New item', description: '' }];
		onedit();
	}

	async function addDimension() {
		const id = await ensureContentId();
		if (!id) return;
		apiError = '';
		const res = await addComparisonDimension(id, {
			label: t('compare.new_dimension', 'New dimension'),
			dimension_type: 'text',
			position: dimensions.length
		});
		if (res.error) {
			apiError = res.error.message;
			return;
		}
		if (res.data)
			dimensions = [
				...dimensions,
				{
					id: res.data.id,
					label: t('compare.new_dimension', 'New dimension'),
					dimension_type: 'text'
				}
			];
		onedit();
	}

	// Server-first removal: call DELETE, then drop the row from local state only
	// after the server confirms (Rule 16 — never mutate server data locally).
	async function removeItem(idx: number) {
		const item = items[idx];
		if (item?.id) {
			apiError = '';
			const res = await deleteComparisonItem(item.id);
			if (res.error) {
				apiError = res.error.message;
				return;
			}
		}
		items = items.filter((_, i) => i !== idx);
		onedit();
	}

	async function removeDimension(idx: number) {
		const dim = dimensions[idx];
		if (dim?.id) {
			apiError = '';
			const res = await deleteComparisonDimension(dim.id);
			if (res.error) {
				apiError = res.error.message;
				return;
			}
		}
		dimensions = dimensions.filter((_, i) => i !== idx);
		onedit();
	}

	// Persist item/dimension title edits on blur (Rule 16 — server is source of
	// truth). Local state updates immediately for responsiveness; the PATCH
	// confirms on blur. Skip the PATCH when the field is empty — the backend
	// rejects empty labels/titles with 400, so we avoid the noise and let the
	// user correct the field inline.
	async function commitItemTitle(idx: number) {
		const item = items[idx];
		if (!item?.id) return;
		if (!item.title.trim()) return; // skip — backend requires non-empty title
		apiError = '';
		const res = await patchComparisonItem(item.id, { title: item.title });
		if (res.error) apiError = res.error.message;
		onedit();
	}

	async function commitDimensionLabel(idx: number) {
		const dim = dimensions[idx];
		if (!dim?.id) return;
		if (!dim.label.trim()) return; // skip — backend requires non-empty label
		apiError = '';
		const res = await patchComparisonDimension(dim.id, { label: dim.label });
		if (res.error) apiError = res.error.message;
		onedit();
	}

	/** Persist a dimension_type change (text|rating|boolean|number|currency).
	 *  Section 30 — the type determines how cell values render and validate.
	 *  The backend PATCH requires both label and dimension_type (label is
	 *  non-nullable), so we send both together. Skip if label is empty. */
	async function commitDimensionType(idx: number) {
		const dim = dimensions[idx];
		if (!dim?.id) return;
		if (!dim.label.trim()) return; // skip — backend requires non-empty label
		apiError = '';
		const res = await patchComparisonDimension(dim.id, {
			label: dim.label,
			dimension_type: dim.dimension_type
		});
		if (res.error) apiError = res.error.message;
		onedit();
	}

	/** Persist an item description edit on blur (Section 30 — items have
	 *  title + description + optional image/geo links). */
	async function commitItemDescription(idx: number) {
		const item = items[idx];
		if (!item?.id) return;
		apiError = '';
		const res = await patchComparisonItem(item.id, { title: item.title, description: item.description });
		if (res.error) apiError = res.error.message;
		onedit();
	}

	/** Auto-generate dimensions from the selected comparison type's field group
	 *  (Section 30 step 4 — "the comparison type's custom field group fields
	 *  become dimension rows"). Uses the heuristic auto-dimensions endpoint
	 *  when no type is selected, or the type's field group when one is. */
	async function applyComparisonType() {
		if (!selectedTypeId) return;
		const type = comparisonTypes.find((t) => t.id === selectedTypeId);
		if (!type) return;
		// Heuristic: use the type's name to suggest dimensions if the type has
		// no field group, otherwise the backend auto-generates from the field
		// group on creation. Since the /create editor creates the comparison
		// via POST /content (not POST /comparisons), we use the auto-dimensions
		// endpoint with the type's item_label as a hint.
		apiError = '';
		const itemNames = items.map((i) => i.title).filter((t) => t);
		if (itemNames.length === 0) {
			// No items yet — just mark dirty; dimensions will be suggested
			// once items are added.
			onedit();
			return;
		}
		const res = await autoGenerateDimensions(itemNames);
		if (res.error) {
			apiError = res.error.message;
			return;
		}
		if (res.data?.dimensions?.length) {
			// Add each suggested dimension that isn't already present.
			const existing = new Set(dimensions.map((d) => d.label.toLowerCase()));
			for (const label of res.data.dimensions) {
				if (existing.has(label.toLowerCase())) continue;
				const id = await ensureContentId();
				if (!id) return;
				const dres = await addComparisonDimension(id, {
					label,
					dimension_type: 'text',
					position: dimensions.length
				});
				if (dres.error) {
					apiError = dres.error.message;
					return;
				}
				if (dres.data) {
					dimensions = [...dimensions, { id: dres.data.id, label, dimension_type: 'text' }];
				}
			}
		}
		onedit();
	}

	// Debounced cell-value write: update local state immediately, but only fire
	// the PUT after 400ms of inactivity (one call per cell edit, not per
	// keystroke).
	function editCell(dimIdx: number, itemIdx: number, value: string) {
		const key = cellKey(dimIdx, itemIdx);
		cells = { ...cells, [key]: value };
		onedit();
		const existing = valueTimers[key];
		if (existing) clearTimeout(existing);
		valueTimers[key] = setTimeout(() => void flushCell(dimIdx, itemIdx), 400);
	}

	async function flushCell(dimIdx: number, itemIdx: number) {
		const dim = dimensions[dimIdx];
		const item = items[itemIdx];
		const key = cellKey(dimIdx, itemIdx);
		delete valueTimers[key];
		if (dim?.id && item?.id) {
			apiError = '';
			const res = await setDimensionValues(dim.id, [{ item_id: item.id, value: cells[key] ?? '' }]);
			if (res.error) apiError = res.error.message;
		}
	}
</script>

<div class="comparison-builder">
	{#if apiError}
		<div class="api-error" role="alert">
			<AlertCircle size={14} />
			<span>{apiError}</span>
		</div>
	{/if}

	<!-- Rich-text body editor — introduction/context above the comparison
	     table. Uses the same Tiptap PostEditor as blog posts so the authoring
	     experience is consistent across content types. -->
	<div class="body-section">
		<PostEditor
			html={bodyHtml}
			defaultMode={defaultEditor}
			onhtml={(v) => { bodyHtml = v; onhtml?.(v); }}
			onedit={onedit}
			onfocus={() => onedit()}
		/>
	</div>

	<!-- Toolbar: comparison type selector + add buttons on one row.
	     The type selector is a compact native select with a custom arrow,
	     sitting inline with the add buttons for a clean, professional look. -->
	<div class="toolbar">
		{#if comparisonTypes.length > 0}
			<div class="type-field">
				<label for="comparison-type" class="type-label">
					{t('create.comparison.type_label', 'Type')}
				</label>
				<div class="select-wrap">
					<select
						id="comparison-type"
						class="type-select"
						value={selectedTypeId}
						onchange={(e) => {
							selectedTypeId = e.currentTarget.value;
							void applyComparisonType();
						}}
					>
						<option value="">{t('create.comparison.type_general', 'General (no type)')}</option>
						{#each comparisonTypes as ct (ct.id)}
							<option value={ct.id}>{ct.name}</option>
						{/each}
					</select>
					<ChevronDown size={14} class="select-arrow" />
				</div>
			</div>
		{/if}
		<div class="action-row">
			<button type="button" class="add-btn" onclick={addItem}>
				<Plus size={14} />
				{t('create.comparison.add_item')}
			</button>
			<button type="button" class="add-btn" onclick={addDimension}>
				<Plus size={14} />
				{t('create.comparison.add_dimension')}
			</button>
		</div>
	</div>

	{#if items.length > 0 || dimensions.length > 0}
		<div class="matrix-wrapper">
			<table class="matrix">
				<thead>
					<tr>
						<th class="corner-cell"></th>
						{#each dimensions as dim, dIdx (dIdx)}
							<th class="dim-header">
								<div class="dim-header-top">
									<input
										type="text"
										class="dim-label-input"
										value={dim.label}
										placeholder={t('compare.new.dimension_placeholder', 'Dimension name')}
										oninput={(e) => {
											dimensions[dIdx].label = e.currentTarget.value;
											onedit();
										}}
										onblur={() => commitDimensionLabel(dIdx)}
									/>
									<button
										type="button"
										class="remove-btn"
										title={t('create.comparison.remove_dimension', 'Remove dimension')}
										onclick={() => removeDimension(dIdx)}
									>
										<X size={13} />
									</button>
								</div>
								<!-- Dimension type selector — Section 30: text|rating|boolean|number|currency.
								     The type determines how cell values render and validate. -->
								<div class="dim-type-wrap">
									<select
										class="dim-type-select"
										value={dim.dimension_type}
										disabled={dimensionTypesError}
										onchange={(e) => {
											dimensions[dIdx].dimension_type = e.currentTarget.value as DimensionType;
											commitDimensionType(dIdx);
										}}
									>
										{#each dimensionTypeOptions as dt (dt)}
											<option value={dt}>{t(`create.comparison.type_${dt}`, dt)}</option>
										{/each}
									</select>
									<ChevronDown size={11} class="dim-type-arrow" />
									{#if dimensionTypesError}
										<span class="dim-type-error" title={t('create.comparison.dimension_types_error', 'Dimension types unavailable')}>
											<AlertCircle size={14} />
										</span>
									{/if}
								</div>
							</th>
						{/each}
					</tr>
				</thead>
				<tbody>
					{#each items as item, iIdx (iIdx)}
						<tr>
							<td class="item-cell">
								<div class="item-header">
									<input
										type="text"
										class="item-title-input"
										value={item.title}
										placeholder={t('create.comparison.item_title_placeholder', 'Item name')}
										oninput={(e) => {
											items[iIdx].title = e.currentTarget.value;
											onedit();
										}}
										onblur={() => commitItemTitle(iIdx)}
									/>
									<button
										type="button"
										class="remove-btn"
										title={t('create.comparison.remove_item', 'Remove item')}
										onclick={() => removeItem(iIdx)}
									>
										<X size={13} />
									</button>
								</div>
								<!-- Item description — Section 30: items have title + description. -->
								<input
									type="text"
									class="item-desc-input"
									placeholder={t('create.comparison.item_description_placeholder', 'Description')}
									value={item.description}
									oninput={(e) => {
										items[iIdx].description = e.currentTarget.value;
										onedit();
									}}
									onblur={() => commitItemDescription(iIdx)}
								/>
							</td>
							{#each dimensions as _, dIdx (dIdx)}
								<td class="value-cell">
									<input
										type="text"
										class="value-input"
										value={cells[cellKey(dIdx, iIdx)] ?? ''}
										placeholder="—"
										oninput={(e) => editCell(dIdx, iIdx, e.currentTarget.value)}
									/>
								</td>
							{/each}
						</tr>
					{/each}
				</tbody>
			</table>
		</div>
		{#if dimensions.length === 0}
			<p class="hint">{t('create.comparison.add_dimension_hint', 'Add a dimension to start filling in values.')}</p>
		{:else if items.length === 0}
			<p class="hint">{t('create.comparison.add_item_hint', 'Add an item to start comparing.')}</p>
		{/if}
	{:else}
		<div class="empty-state">
			<div class="empty-icon">
				<TableIcon size={32} />
			</div>
			<p class="empty-text">{t('create.comparison.empty')}</p>
		</div>
	{/if}
</div>

