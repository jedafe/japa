TENANT_ID = "00000000-0000-0000-0000-000000000001"
SUPER_ADMIN_GROUP = "00000000-0000-0000-0000-000000000010"


def create_config(tool_type, label, action):
    fn = f"{tool_type}.{action}"
    if action == "create":
        params = {
            "type": "object",
            "description": f"Fields for the new {label} record",
            "properties": {
                "payload": {
                    "type": "object",
                    "description": "Tool record fields",
                    "additionalProperties": True,
                }
            },
            "additionalProperties": True,
        }
    else:
        params = {
            "type": "object",
            "properties": {
                "tool_id": {"type": "string", "description": "UUID of the record"},
                "payload": {
                    "type": "object",
                    "description": "Fields to update",
                    "additionalProperties": True,
                },
            },
            "required": ["tool_id"],
            "additionalProperties": True,
        }
    return {
        "function_name": fn,
        "description": f"{action.capitalize()} a {label} record",
        "handler": fn,
        "parameters": params,
        "writes_user_data": True,
        "requires_hitl": False,
    }


def main():
    if len(sys.argv) != 2:
        print("usage: generate_tool_crud_migration.py <out.sql>")
        sys.exit(1)
    out = sys.argv[1]

    lines = [
        "-- Dedicated AI tool CRUD migration",
        "-- Generated by scripts/generate_tool_crud_migration.py",
        "",
        "BEGIN;",
        "",
    ]

    # Upsert permission nodes for .manage
    for tool_type, label, _, perm in TOOLS:
        lines.append(
            f"INSERT INTO permissions (key, description) VALUES ('{perm}', 'Manage {label}') "
            f"ON CONFLICT (key) DO UPDATE SET description = EXCLUDED.description;"
        )

    lines.append("")
    lines.append("-- Grant .manage permissions to all roles in the Super Admin group")
    lines.append(
        f"INSERT INTO role_permissions (role_id, permission_id)"
        f" SELECT gr.role_id, p.id FROM group_roles gr"
        f" JOIN permissions p ON p.key LIKE '%.manage'"
        f" WHERE gr.group_id = '{SUPER_ADMIN_GROUP}'"
        f" ON CONFLICT (role_id, permission_id) DO NOTHING;"
    )
    lines.append("")

    # Insert ai_tools rows
    for tool_type, label, category, perm in TOOLS:
        for action in ("create", "update", "delete", "assign_geo"):
            fn = f"{tool_type}.{action}"
            desc = f"{action.capitalize()} a {label} record."
            if action == "create":
                desc = f"Create a new {label} record."
            elif action == "update":
                desc = f"Update an existing {label} record."
            elif action == "delete":
                desc = f"Soft-delete an existing {label} record."
            elif action == "assign_geo":
                desc = f"Assign/update the geo scope of an existing {label} record."
            config = json.dumps(create_config(tool_type, label, action), separators=(",", ":"))
            lines.append(
                f"INSERT INTO ai_tools (tenant_id, name, description, category, config, is_enabled, required_permission)"
                f" VALUES ('{TENANT_ID}', '{fn}', '{desc}', 'agent_{category}', '{config}'::jsonb, true, '{perm}')"
                f" ON CONFLICT (tenant_id, name) DO UPDATE SET"
                f" description = EXCLUDED.description,"
                f" category = EXCLUDED.category,"
                f" config = EXCLUDED.config,"
                f" is_enabled = EXCLUDED.is_enabled,"
                f" required_permission = EXCLUDED.required_permission;"
            )

    lines.append("")
    lines.append("COMMIT;")

    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
