-- 000782_travel_airlines_directory.up.sql
-- §67 Travel Search / ADR-124 second extension:
--   * travel_airlines — global airline catalog (OpenFlights dataset, active
--     carriers with IATA codes) with code-reassignment patches for current
--     operators the stale dataset mis-maps (P4=Air Peace, QI=Ibom Air,
--     U5=United Nigeria, VM=Max Air, 9J=Dana Air, Q9=Green Africa,
--     VK=ValueJet, JM=Jambojet, FN=Fastjet, UR=Uganda Airlines, KP=ASKY,
--     HF=Air Côte d'Ivoire, FA=FlySafair, ZB=Air Albania, W3=Arik Air
--     reactivated; plus name/icao-keyed Rano Air and Air Sénégal whose
--     codes collide). Self-maintaining: offer persistence upserts
--     provider-observed airlines that miss the seed.
--   * travel_provider_airlines — coverage join integrating the catalog
--     with travel_providers: which configured provider's offers have been
--     observed carrying each airline.
--   * travel_flight_offers.airline_key — offer → entity FK (raw provider
--     airline string retained alongside).
--
-- airline_key = 'iata:XX' | 'icao:XXX' | 'name:{slug}'. iata_code is
-- intentionally non-unique (IATA reuses codes).
--
-- Ref: japaconnect-engineering/sections/67-travel-search.md
--      japaconnect-engineering/adr/ADR-124-travel-offer-inventory.md

BEGIN;

CREATE TABLE travel_airlines (
    airline_key   text PRIMARY KEY,
    iata_code     text,
    icao_code     text,
    name          text NOT NULL,
    country       text NOT NULL DEFAULT '',
    source        text NOT NULL DEFAULT 'seed'
                  CHECK (source IN ('seed','observed')),
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at  timestamptz
);

CREATE INDEX idx_travel_airlines_iata    ON travel_airlines (iata_code) WHERE iata_code IS NOT NULL;
CREATE INDEX idx_travel_airlines_name    ON travel_airlines (name text_pattern_ops);
CREATE INDEX idx_travel_airlines_country ON travel_airlines (country text_pattern_ops);

CREATE TABLE travel_provider_airlines (
    provider_id   uuid NOT NULL REFERENCES travel_providers(id) ON DELETE CASCADE,
    airline_key   text NOT NULL REFERENCES travel_airlines(airline_key) ON DELETE CASCADE,
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (provider_id, airline_key)
);
CREATE INDEX idx_travel_provider_airlines_key ON travel_provider_airlines (airline_key);

ALTER TABLE travel_flight_offers
    ADD COLUMN airline_key text REFERENCES travel_airlines(airline_key) ON DELETE SET NULL;
CREATE INDEX idx_travel_flight_offers_airline ON travel_flight_offers (airline_key) WHERE airline_key IS NOT NULL;

