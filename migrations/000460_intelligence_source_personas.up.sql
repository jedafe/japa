-- 000460_intelligence_source_personas.up.sql
-- Attaches an AI persona to each intelligence source so promoted content is
-- authored by the persona's backing bot user (ADR-068). Fixes the FK violation
-- where the promoter stamped defaultTenantID as contents.author_id.
--
-- 1. Adds persona_id column to intel_sources (nullable, FK → ai_personas).
-- 2. Seeds a "contributor" professional_profile_type (required by the persona
--    provisioning service as the default byline type).
-- 3. Seeds 16 AI personas — one per intelligence category — with realistic
--    human names from different countries. Each persona gets a backing bot
--    user (is_bot = true), a professional profile byline, and an ai_personas
--    config row (disclosed, autonomous).
-- 4. Attaches each persona to all intel_sources of the matching category.
-- 5. Seeds the intel.default_persona_id system setting (fallback for sources
--    without an explicit persona).
-- Ref: ADR-068, ADR-112, docs/superpowers/plans/2026-08-12-japa-intelligence-system.md

BEGIN;

-- =====================================================================
-- 1. Add persona_id to intel_sources
-- =====================================================================
ALTER TABLE intel_sources ADD COLUMN IF NOT EXISTS persona_id uuid;
ALTER TABLE intel_sources
  DROP CONSTRAINT IF EXISTS intel_sources_persona_id_fkey;
ALTER TABLE intel_sources
  ADD CONSTRAINT intel_sources_persona_id_fkey
  FOREIGN KEY (persona_id) REFERENCES ai_personas(id) ON DELETE SET NULL;

-- =====================================================================
-- 2. Seed "contributor" profile type (needed by persona provisioning)
-- =====================================================================
INSERT INTO professional_profile_types (tenant_id, name, slug, icon, is_system)
VALUES ('00000000-0000-0000-0000-000000000001', 'Contributor', 'contributor', 'user', true)
ON CONFLICT (tenant_id, slug) DO NOTHING;

-- =====================================================================
-- 3. Seed 16 AI personas — one per intelligence category.
--    Each persona = bot user + professional profile + ai_personas config.
--    The super admin (jedafeglobal@gmail.com) is the created_by.
-- =====================================================================

-- Resolve the super admin user ID for created_by.
-- We use a CTE to avoid hardcoding a UUID that was generated by gen_random_uuid().
WITH admin_user AS (
    SELECT id FROM users
    WHERE tenant_id = '00000000-0000-0000-0000-000000000001'
      AND email = 'jedafeglobal@gmail.com'
    LIMIT 1
),
contributor_type AS (
    SELECT id FROM professional_profile_types
    WHERE tenant_id = '00000000-0000-0000-0000-000000000001'
      AND slug = 'contributor'
    LIMIT 1
),
-- Create 16 bot users — one per category. Deterministic emails for idempotency.
bot_users AS (
    INSERT INTO users (tenant_id, email, username, profile_type, status, is_bot)
    SELECT '00000000-0000-0000-0000-000000000001', email, username, 'professional', 'active', true
    FROM (VALUES
        ('intel-scholarship@bot.internal',       'intel-scholarship'),
        ('intel-job@bot.internal',               'intel-job'),
        ('intel-visa@bot.internal',              'intel-visa'),
        ('intel-fx@bot.internal',                'intel-fx'),
        ('intel-remittance@bot.internal',        'intel-remittance'),
        ('intel-news@bot.internal',              'intel-news'),
        ('intel-travel-alert@bot.internal',      'intel-travel-alert'),
        ('intel-housing@bot.internal',           'intel-housing'),
        ('intel-cost-of-living@bot.internal',    'intel-cost-of-living'),
        ('intel-travel-routes@bot.internal',     'intel-travel-routes'),
        ('intel-grants@bot.internal',            'intel-grants'),
        ('intel-admission@bot.internal',         'intel-admission'),
        ('intel-banking@bot.internal',           'intel-banking'),
        ('intel-work-career@bot.internal',       'intel-work-career'),
        ('intel-health-insurance@bot.internal',  'intel-health-insurance'),
        ('intel-culture-lifestyle@bot.internal', 'intel-culture-lifestyle')
    ) AS t(email, username)
    ON CONFLICT (tenant_id, email) DO NOTHING
    RETURNING id, email
),
-- Merge with existing users (for re-runs where users already exist).
all_bot_users AS (
    SELECT id, email FROM bot_users
    UNION
    SELECT id, email FROM users
    WHERE tenant_id = '00000000-0000-0000-0000-000000000001'
      AND email LIKE 'intel-%@bot.internal'
),
-- Create 16 professional profiles — the public bylines with human names.
bot_profiles AS (
    INSERT INTO professional_profiles (tenant_id, owner_user_id, type_id, name, slug, tagline, field_values)
    SELECT
        '00000000-0000-0000-0000-000000000001',
        u.id,
        (SELECT id FROM contributor_type),
        p.name,
        p.slug,
        p.tagline,
        '{}'::jsonb
    FROM all_bot_users u
    JOIN (VALUES
        ('intel-scholarship@bot.internal',       'Amara Diallo',      'intel-scholarship',       'Scholarship Scout'),
        ('intel-job@bot.internal',               'Kwame Mensah',      'intel-job',               'Job Market Analyst'),
        ('intel-visa@bot.internal',              'Hiroshi Tanaka',    'intel-visa',              'Visa Route Analyst'),
        ('intel-fx@bot.internal',                'Zhang Wei',         'intel-fx',                'FX Rate Tracker'),
        ('intel-remittance@bot.internal',        'Priya Patel',       'intel-remittance',        'Remittance Analyst'),
        ('intel-news@bot.internal',              'Fatima Al-Rashid',  'intel-news',              'News Correspondent'),
        ('intel-travel-alert@bot.internal',      'Carlos Mendoza',    'intel-travel-alert',      'Travel Alert Monitor'),
        ('intel-housing@bot.internal',           'Sven Lindqvist',    'intel-housing',           'Housing Guide Scout'),
        ('intel-cost-of-living@bot.internal',    'Anya Volkov',       'intel-cost-of-living',    'Cost of Living Analyst'),
        ('intel-travel-routes@bot.internal',     'Liam O''Connor',    'intel-travel-routes',     'Travel Routes Scout'),
        ('intel-grants@bot.internal',            'Nadia Hassan',      'intel-grants',            'Grants Researcher'),
        ('intel-admission@bot.internal',         'Yuki Yamamoto',     'intel-admission',         'Admission Guide Analyst'),
        ('intel-banking@bot.internal',           'Tunde Adebayo',     'intel-banking',           'Banking Guide Analyst'),
        ('intel-work-career@bot.internal',       'Sofia Rossi',       'intel-work-career',       'Work & Career Analyst'),
        ('intel-health-insurance@bot.internal',  'Ingrid Larsen',     'intel-health-insurance',  'Health Insurance Analyst'),
        ('intel-culture-lifestyle@bot.internal', 'Maya Singh',       'intel-culture-lifestyle', 'Culture & Lifestyle Scout')
    ) AS p(email, name, slug, tagline) ON u.email = p.email
    ON CONFLICT (slug) DO NOTHING
    RETURNING id, slug
),
-- Merge with existing profiles (for re-runs).
all_bot_profiles AS (
    SELECT id, slug FROM bot_profiles
    UNION
    SELECT id, slug FROM professional_profiles
    WHERE tenant_id = '00000000-0000-0000-0000-000000000001'
      AND slug LIKE 'intel-%'
),
-- Create 16 ai_personas config rows.
bot_personas AS (
    INSERT INTO ai_personas (tenant_id, user_id, profile_id, disclosure_mode, autonomy_mode, activity_policy, status, created_by)
    SELECT
        '00000000-0000-0000-0000-000000000001',
        u.id,
        pr.id,
        'disclosed',
        'autonomous',
        '{}'::jsonb,
        'active',
        (SELECT id FROM admin_user)
    FROM all_bot_users u
    JOIN all_bot_profiles pr ON pr.slug = REPLACE(u.email, '@bot.internal', '')
    WHERE u.email LIKE 'intel-%@bot.internal'
    ON CONFLICT (user_id) DO NOTHING
    RETURNING id, user_id
)
SELECT 1; -- terminal SELECT to complete the CTE chain

COMMIT;

-- =====================================================================
-- 4. Attach personas to sources by category.
--    Separate transaction so the persona data from the CTE chain above is
--    committed and visible to this UPDATE (PostgreSQL data-modifying CTEs
--    are not visible to subsequent statements in the same snapshot).
-- =====================================================================
BEGIN;

UPDATE intel_sources s
SET persona_id = (
    SELECT ap.id FROM ai_personas ap
    JOIN users u ON u.id = ap.user_id
    WHERE ap.tenant_id = s.tenant_id
      AND u.email = CASE s.category
        WHEN 'scholarship'       THEN 'intel-scholarship@bot.internal'
        WHEN 'job'               THEN 'intel-job@bot.internal'
        WHEN 'visa'              THEN 'intel-visa@bot.internal'
        WHEN 'fx'                THEN 'intel-fx@bot.internal'
        WHEN 'remittance'        THEN 'intel-remittance@bot.internal'
        WHEN 'news'              THEN 'intel-news@bot.internal'
        WHEN 'travel_alert'      THEN 'intel-travel-alert@bot.internal'
        WHEN 'housing'           THEN 'intel-housing@bot.internal'
        WHEN 'cost_of_living'    THEN 'intel-cost-of-living@bot.internal'
        WHEN 'travel_routes'     THEN 'intel-travel-routes@bot.internal'
        WHEN 'grants'            THEN 'intel-grants@bot.internal'
        WHEN 'admission'         THEN 'intel-admission@bot.internal'
        WHEN 'banking'           THEN 'intel-banking@bot.internal'
        WHEN 'work_career'       THEN 'intel-work-career@bot.internal'
        WHEN 'health_insurance'  THEN 'intel-health-insurance@bot.internal'
        WHEN 'culture_lifestyle' THEN 'intel-culture-lifestyle@bot.internal'
      END
    LIMIT 1
)
WHERE s.persona_id IS NULL
  AND s.category IN ('scholarship','job','visa','fx','remittance','news',
    'travel_alert','housing','cost_of_living','travel_routes','grants',
    'admission','banking','work_career','health_insurance','culture_lifestyle');

-- =====================================================================
-- 5. Seed intel.default_persona_id system setting (fallback).
--    Points to the scholarship persona as the default.
-- =====================================================================
INSERT INTO system_settings (tenant_id, key, value)
SELECT
    '00000000-0000-0000-0000-000000000001',
    'intel.default_persona_id',
    to_jsonb(ap.id::text)
FROM ai_personas ap
JOIN users u ON u.id = ap.user_id
WHERE ap.tenant_id = '00000000-0000-0000-0000-000000000001'
  AND u.email = 'intel-scholarship@bot.internal'
LIMIT 1
ON CONFLICT (tenant_id, key) DO NOTHING;

COMMIT;
