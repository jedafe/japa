-- 000510_comment_votes_pk_conformance.up.sql
-- BUG-008: Brings comment_votes into schema conformance with Section 49.
-- The spec defines PRIMARY KEY (comment_id, user_id) with no surrogate id
-- column. Migration 000103 created an extra `id uuid PRIMARY KEY` column
-- plus a UNIQUE(comment_id, user_id) constraint. This migration:
--   1. Drops the id-based PRIMARY KEY
--   2. Drops the id column
--   3. Drops the UNIQUE(comment_id, user_id) constraint
--   4. Adds PRIMARY KEY (comment_id, user_id)
-- tenant_id is retained (not in the spec's simplified schema but required
-- for multi-tenant query scoping — see Guide §4.2/§9).
-- Ref: japaconnect-engineering/sections/49-comments-replies.md

BEGIN;

-- Drop the existing PRIMARY KEY constraint on the id column.
-- The constraint name is auto-generated by PostgreSQL as <table>_pkey.
ALTER TABLE comment_votes DROP CONSTRAINT IF EXISTS comment_votes_pkey;

-- Drop the UNIQUE(comment_id, user_id) constraint.
-- The constraint name is auto-generated as comment_votes_comment_id_user_id_key.
ALTER TABLE comment_votes DROP CONSTRAINT IF EXISTS comment_votes_comment_id_user_id_key;

-- Drop the id column (no longer needed — composite PK replaces it).
ALTER TABLE comment_votes DROP COLUMN IF EXISTS id;

-- Add the Section 49 composite primary key.
ALTER TABLE comment_votes
    ADD CONSTRAINT comment_votes_pkey
    PRIMARY KEY (comment_id, user_id);

COMMIT;
