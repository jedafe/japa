-- Phase 33: Coupons & External Affiliate Providers (Section 55)
-- Phase 34: User Affiliate Program (Section 56)

-- External affiliate and coupon providers (admin-managed)
CREATE TABLE affiliate_providers (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id       uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    name            text NOT NULL,
    slug            text NOT NULL,
    description     text,
    provider_type   text NOT NULL DEFAULT 'affiliate'
                      CHECK (provider_type IN ('affiliate', 'coupon', 'both')),
    logo_media_id   uuid REFERENCES media(id) ON DELETE SET NULL,
    base_url        text,
    tracking_param  text,
    tracking_value  text,
    commission_rate numeric(5,2),
    is_active       boolean NOT NULL DEFAULT true,
    is_featured     boolean NOT NULL DEFAULT false,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE(tenant_id, slug)
);
CREATE INDEX idx_affiliate_providers_active ON affiliate_providers (tenant_id, is_active);

-- Coupon codes (both external partner coupons and internal JapaConnect coupons)
CREATE TABLE coupons (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id       uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    provider_id     uuid REFERENCES affiliate_providers(id) ON DELETE SET NULL,
    coupon_type     text NOT NULL DEFAULT 'external'
                      CHECK (coupon_type IN ('external', 'internal')),
    title           text NOT NULL,
    description     text,
    code            text NOT NULL,
    discount_type   text
                      CHECK (discount_type IN ('percent', 'fixed', 'free_shipping', NULL)),
    discount_value  numeric,
    currency        text,
    terms_url       text,
    referral_url    text,
    is_verified     boolean NOT NULL DEFAULT false,
    status          text NOT NULL DEFAULT 'active'
                      CHECK (status IN ('active', 'expired', 'suspended')),
    valid_from      timestamptz,
    expires_at      timestamptz,
    total_clicks    int NOT NULL DEFAULT 0,
    total_copies    int NOT NULL DEFAULT 0,
    created_by      uuid REFERENCES users(id) ON DELETE SET NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE(tenant_id, code)
);
CREATE INDEX idx_coupons_active   ON coupons (tenant_id, status, expires_at);
CREATE INDEX idx_coupons_provider ON coupons (provider_id, status);

-- Click and copy events per coupon
CREATE TABLE coupon_events (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    coupon_id    uuid NOT NULL REFERENCES coupons(id) ON DELETE CASCADE,
    event_type   text NOT NULL CHECK (event_type IN ('click', 'copy')),
    user_id      uuid REFERENCES users(id) ON DELETE SET NULL,
    content_id   uuid REFERENCES contents(id) ON DELETE SET NULL,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_coupon_events_coupon ON coupon_events (coupon_id, event_type, created_at DESC);

-- User affiliate program enrollment
CREATE TABLE affiliate_program_members (
    user_id           uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    tenant_id         uuid NOT NULL REFERENCES tenants(id),
    enrolled_at       timestamptz NOT NULL DEFAULT now(),
    status            text NOT NULL DEFAULT 'active'
                        CHECK (status IN ('active', 'suspended', 'banned')),
    total_clicks      int NOT NULL DEFAULT 0,
    total_conversions int NOT NULL DEFAULT 0,
    total_earned_credits numeric(12,2) NOT NULL DEFAULT 0,
    payout_method     text,
    notes             text
);

-- Affiliate links generated by enrolled users
CREATE TABLE user_affiliate_links (
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id        uuid NOT NULL REFERENCES tenants(id),
    user_id          uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_type     text NOT NULL
                       CHECK (product_type IN ('pro_subscription', 'course', 'general')),
    product_id       uuid,
    code             text NOT NULL UNIQUE,
    description      text,
    destination_url  text NOT NULL,
    click_count      int NOT NULL DEFAULT 0,
    conversion_count int NOT NULL DEFAULT 0,
    total_earned     numeric(12,2) NOT NULL DEFAULT 0,
    is_active        boolean NOT NULL DEFAULT true,
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_ual_user ON user_affiliate_links (user_id, is_active);
CREATE INDEX idx_ual_code ON user_affiliate_links (code);

-- Individual click and conversion events
CREATE TABLE affiliate_link_events (
    id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id            uuid NOT NULL REFERENCES tenants(id),
    link_id              uuid NOT NULL REFERENCES user_affiliate_links(id) ON DELETE CASCADE,
    event_type           text NOT NULL CHECK (event_type IN ('click', 'conversion')),
    referrer_url         text,
    ip_hash              text,
    user_agent_hash      text,
    converted_payment_id uuid REFERENCES payments(id) ON DELETE SET NULL,
    commission_amount    numeric(12,2),
    created_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_ale_link  ON affiliate_link_events (link_id, event_type, created_at DESC);
CREATE INDEX idx_ale_dedup ON affiliate_link_events (link_id, ip_hash, created_at DESC);
